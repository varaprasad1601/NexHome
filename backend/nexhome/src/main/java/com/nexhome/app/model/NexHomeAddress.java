package com.nexhome.app.model;

import java.math.BigDecimal;
import java.time.Instant;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * A customer's service location; a customer may have several. At most one is the default, enforced by the partial
 * unique index {@code ux_nexhome_addresses_one_default}. Latitude and longitude are both set or both empty.
 */
@Entity
@Table(name = "nexhome_addresses")
@Getter
@Setter
@NoArgsConstructor
public class NexHomeAddress {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Column(name = "id")
	private Long id;

	// Generated by the database (column default), e.g. NHADDR0001; never written by the application
	@Generated
	@Column(name = "public_id", nullable = false, insertable = false, updatable = false, length = 24)
	private String publicId;

	// The owner is fixed once the record is created
	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "user_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomeUser user;

	@Column(name = "contact_name", nullable = false, length = 150)
	private String contactName;

	@Column(name = "mobile_number", nullable = false, length = 15)
	private String mobileNumber;

	/** ADDRESS_TYPE lookup code. */
	@Column(name = "address_type", nullable = false, length = 60)
	private String addressType;

	@Column(name = "label", length = 50)
	private String label;

	@Column(name = "address_line1", nullable = false, length = 255)
	private String addressLine1;

	@Column(name = "address_line2")
	private String addressLine2;

	@Column(name = "landmark")
	private String landmark;

	@Column(name = "city", nullable = false, length = 100)
	private String city;

	@Column(name = "state", nullable = false, length = 100)
	private String state;

	@Column(name = "postal_code", nullable = false, length = 12)
	private String postalCode;

	/** ISO 3166 alpha-2 country, e.g. IN. */
	@Column(name = "country_code", nullable = false, length = 2)
	private String countryCode = "IN";

	@Column(name = "latitude", precision = 10, scale = 7)
	private BigDecimal latitude;

	@Column(name = "longitude", precision = 10, scale = 7)
	private BigDecimal longitude;

	@Column(name = "is_default", nullable = false)
	private boolean defaultAddress = false;

	@CreationTimestamp
	@Column(name = "creation_date", nullable = false, updatable = false)
	private Instant creationDate;

	@Column(name = "created_by", updatable = false)
	private Long createdBy;

	@UpdateTimestamp
	@Column(name = "updated_date", nullable = false)
	private Instant updatedDate;

	@Column(name = "updated_by")
	private Long updatedBy;

	@Column(name = "attribute1")
	private String attribute1;

	@Column(name = "attribute2")
	private String attribute2;

	@Column(name = "attribute3")
	private String attribute3;

	@Column(name = "attribute4")
	private String attribute4;

	@Column(name = "attribute5")
	private String attribute5;
}
