package com.nexhome.app.model;

import java.time.Instant;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * A support request (Module 9). The requester owns it; {@code created_by} is whoever opened it (staff may open one
 * on a user's behalf). Category, priority and status are SUPPORT_CATEGORY, SUPPORT_PRIORITY and
 * SUPPORT_TICKET_STATUS value codes.
 */
@Entity
@Table(name = "nexhome_support_tickets")
@Getter
@Setter
@NoArgsConstructor
public class NexHomeSupportTicket {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Column(name = "id")
	private Long id;

	// Generated by the database (column default), e.g. NHTICK0001; never written by the application
	@Generated
	@Column(name = "public_id", nullable = false, insertable = false, updatable = false, length = 24)
	private String publicId;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "requester_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomeUser requester;

	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "booking_id", referencedColumnName = "id", updatable = false)
	private NexHomeBooking booking;

	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "payment_id", referencedColumnName = "id", updatable = false)
	private NexHomePayment payment;

	@Column(name = "category", nullable = false, length = 40)
	private String category;

	@Column(name = "subject", nullable = false, length = 200)
	private String subject;

	@Column(name = "description", nullable = false, columnDefinition = "text")
	private String description;

	@Column(name = "priority", nullable = false, length = 60)
	private String priority;

	@Column(name = "status", nullable = false, length = 60)
	private String status;

	/** The staff member handling it. */
	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "assigned_to", referencedColumnName = "id")
	private NexHomeUser assignedTo;

	@Column(name = "resolved_at")
	private Instant resolvedAt;

	@Column(name = "closed_at")
	private Instant closedAt;

	@CreationTimestamp
	@Column(name = "creation_date", nullable = false, updatable = false)
	private Instant creationDate;

	@Column(name = "created_by", updatable = false)
	private Long createdBy;

	@UpdateTimestamp
	@Column(name = "updated_date", nullable = false)
	private Instant updatedDate;

	@Column(name = "updated_by")
	private Long updatedBy;

	@Column(name = "attribute1")
	private String attribute1;

	@Column(name = "attribute2")
	private String attribute2;

	@Column(name = "attribute3")
	private String attribute3;

	@Column(name = "attribute4")
	private String attribute4;

	@Column(name = "attribute5")
	private String attribute5;
}
