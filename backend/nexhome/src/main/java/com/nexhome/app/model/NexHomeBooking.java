package com.nexhome.app.model;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.annotations.UpdateTimestamp;
import org.hibernate.type.SqlTypes;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * A booked service: who, what, where and when, with snapshots of the service name, address and price that
 * survive catalogue and address changes. Status changes are recorded in {@link NexHomeBookingStatusHistory}.
 */
@Entity
@Table(name = "nexhome_bookings")
@Getter
@Setter
@NoArgsConstructor
public class NexHomeBooking {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Column(name = "id")
	private Long id;

	// Generated by the database (column default), e.g. NHBOOK0001; never written by the application
	@Generated
	@Column(name = "public_id", nullable = false, insertable = false, updatable = false, length = 24)
	private String publicId;

	/** Groups the bookings of one checkout. */
	@Column(name = "checkout_id", updatable = false)
	private UUID checkoutId;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "customer_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomeCustomerProfile customer;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "service_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomeService service;

	/** Null once the variant is removed from the catalogue (the snapshots keep its name and price). */
	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "variant_id", referencedColumnName = "id")
	private NexHomeServiceVariant variant;

	/** The partner who accepted the booking. */
	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "partner_id", referencedColumnName = "id")
	private NexHomePartnerProfile partner;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "address_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomeAddress address;

	/** BOOKING_TYPE lookup code. */
	@Column(name = "booking_type", nullable = false, updatable = false, length = 60)
	private String bookingType;

	/** BOOKING_STATUS lookup code. */
	@Column(name = "booking_status", nullable = false, length = 60)
	private String bookingStatus;

	/** BOOKING_PAYMENT_STATUS lookup code; null once the booking is CANCELLED (V42). */
	@Column(name = "payment_status", length = 60)
	private String paymentStatus;

	/** PAYMENT_METHOD lookup code. */
	@Column(name = "payment_method", nullable = false, length = 60)
	private String paymentMethod;

	/** Null for an INSTANT booking (as soon as possible, V33); required for SCHEDULED. */
	@Column(name = "scheduled_start_at")
	private Instant scheduledStartAt;

	@Column(name = "scheduled_end_at")
	private Instant scheduledEndAt;

	@Column(name = "actual_start_at")
	private Instant actualStartAt;

	@Column(name = "actual_end_at")
	private Instant actualEndAt;

	@Column(name = "service_name_snapshot", nullable = false, length = 150)
	private String serviceNameSnapshot;

	/** The address as it was when booked (JSON object). */
	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "address_snapshot", nullable = false, columnDefinition = "jsonb")
	private String addressSnapshot;

	/** The price quote it was booked at, and the final one once an hourly job ends (JSON object). */
	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "pricing_snapshot", nullable = false, columnDefinition = "jsonb")
	private String pricingSnapshot;

	@Column(name = "subtotal_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal subtotalAmount;

	@Column(name = "discount_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal discountAmount;

	@Column(name = "tax_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal taxAmount;

	/** The online payment fee charged with the booking (V35; 0 for cash); part of the total, never refunded. */
	@Column(name = "transaction_fee_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal transactionFeeAmount = BigDecimal.ZERO;

	@Column(name = "total_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal totalAmount;

	@JdbcTypeCode(SqlTypes.CHAR)
	@Column(name = "currency", nullable = false, length = 3)
	private String currency = "INR";

	@Column(name = "cancellation_reason", columnDefinition = "text")
	private String cancellationReason;

	@CreationTimestamp
	@Column(name = "creation_date", nullable = false, updatable = false)
	private Instant creationDate;

	@Column(name = "created_by", updatable = false)
	private Long createdBy;

	@UpdateTimestamp
	@Column(name = "updated_date", nullable = false)
	private Instant updatedDate;

	@Column(name = "updated_by")
	private Long updatedBy;

	@Column(name = "attribute1")
	private String attribute1;

	@Column(name = "attribute2")
	private String attribute2;

	@Column(name = "attribute3")
	private String attribute3;

	@Column(name = "attribute4")
	private String attribute4;

	@Column(name = "attribute5")
	private String attribute5;
}
