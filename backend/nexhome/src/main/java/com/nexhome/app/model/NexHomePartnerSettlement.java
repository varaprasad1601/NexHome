package com.nexhome.app.model;

import java.math.BigDecimal;
import java.time.Instant;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * A partner's wallet paid out in one transfer (V60, not in the PDF): the online jobs' payouts less the commission
 * owed on the cash jobs the partner collected. Its payouts and cash collections point at it.
 */
@Entity
@Table(name = "nexhome_partner_settlements")
@Getter
@Setter
@NoArgsConstructor
public class NexHomePartnerSettlement {

	public static final String PAID = "PAID";
	public static final String FAILED = "FAILED";

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Column(name = "id")
	private Long id;

	// Generated by the database (column default), e.g. NHSETL0001; never written by the application
	@Generated
	@Column(name = "public_id", nullable = false, insertable = false, updatable = false, length = 24)
	private String publicId;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "partner_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomePartnerProfile partner;

	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "bank_account_id", referencedColumnName = "id")
	private NexHomePartnerBankAccount bankAccount;

	@Column(name = "bank_account_last4", length = 4)
	private String bankAccountLast4;

	@Column(name = "bank_name", length = 150)
	private String bankName;

	@Column(name = "cash_jobs", nullable = false)
	private Integer cashJobs;

	@Column(name = "cash_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal cashAmount;

	@Column(name = "cash_commission", nullable = false, precision = 12, scale = 2)
	private BigDecimal cashCommission;

	@Column(name = "online_jobs", nullable = false)
	private Integer onlineJobs;

	@Column(name = "online_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal onlineAmount;

	@Column(name = "online_commission", nullable = false, precision = 12, scale = 2)
	private BigDecimal onlineCommission;

	@Column(name = "adjustments_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal adjustmentsAmount;

	@Column(name = "net_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal netAmount;

	/** PAID or FAILED. */
	@Column(name = "settlement_status", nullable = false, length = 20)
	private String settlementStatus;

	@Column(name = "provider_transfer_id", length = 150)
	private String providerTransferId;

	@org.hibernate.annotations.JdbcTypeCode(org.hibernate.type.SqlTypes.JSON)
	@Column(name = "provider_response", columnDefinition = "jsonb")
	private String providerResponse;

	@Column(name = "paid_at")
	private Instant paidAt;

	@CreationTimestamp
	@Column(name = "creation_date", nullable = false, updatable = false)
	private Instant creationDate;

	@Column(name = "created_by", updatable = false)
	private Long createdBy;

	@UpdateTimestamp
	@Column(name = "updated_date", nullable = false)
	private Instant updatedDate;

	@Column(name = "updated_by")
	private Long updatedBy;

	@Column(name = "attribute1")
	private String attribute1;

	@Column(name = "attribute2")
	private String attribute2;

	@Column(name = "attribute3")
	private String attribute3;

	@Column(name = "attribute4")
	private String attribute4;

	@Column(name = "attribute5")
	private String attribute5;
}
