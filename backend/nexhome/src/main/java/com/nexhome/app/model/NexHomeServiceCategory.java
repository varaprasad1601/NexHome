package com.nexhome.app.model;

import java.time.Instant;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * A top-level service category, e.g. Cleaning. Categories that services use are deactivated, not deleted.
 */
@Entity
@Table(name = "nexhome_service_categories")
@Getter
@Setter
@NoArgsConstructor
public class NexHomeServiceCategory {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Column(name = "id")
	private Long id;

	// Generated by the database (column default), e.g. NHCATG0001; never written by the application
	@Generated
	@Column(name = "public_id", nullable = false, insertable = false, updatable = false, length = 24)
	private String publicId;

	@Column(name = "name", nullable = false, length = 120)
	private String name;

	/** Lower-case words joined by hyphens, unique; used in URLs. */
	@Column(name = "slug", nullable = false, unique = true, length = 150)
	private String slug;

	@Column(name = "description", columnDefinition = "text")
	private String description;

	@Column(name = "icon_url", columnDefinition = "text")
	private String iconUrl;

	@Column(name = "display_order", nullable = false)
	private int displayOrder = 0;

	@Column(name = "is_active", nullable = false)
	private boolean active = true;

	@CreationTimestamp
	@Column(name = "creation_date", nullable = false, updatable = false)
	private Instant creationDate;

	@Column(name = "created_by", updatable = false)
	private Long createdBy;

	@UpdateTimestamp
	@Column(name = "updated_date", nullable = false)
	private Instant updatedDate;

	@Column(name = "updated_by")
	private Long updatedBy;

	@Column(name = "attribute1")
	private String attribute1;

	@Column(name = "attribute2")
	private String attribute2;

	@Column(name = "attribute3")
	private String attribute3;

	@Column(name = "attribute4")
	private String attribute4;

	@Column(name = "attribute5")
	private String attribute5;
}
