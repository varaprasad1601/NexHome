package com.nexhome.app.model;

import java.math.BigDecimal;
import java.time.Instant;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * A bookable service with its default price and the platform's commission. Variants may override the price and
 * duration; media and requirements describe it. The price is snapshotted when a booking is created.
 * <p>
 * Check constraints: HOURLY pricing needs the minimum billable minutes and billing increment; a PERCENTAGE commission
 * is at most 100; at least one of instant and scheduled booking is allowed.
 */
@Entity
@Table(name = "nexhome_services")
@Getter
@Setter
@NoArgsConstructor
public class NexHomeService {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Column(name = "id")
	private Long id;

	// Generated by the database (column default), e.g. NHSERV0001; never written by the application
	@Generated
	@Column(name = "public_id", nullable = false, insertable = false, updatable = false, length = 24)
	private String publicId;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "category_id", referencedColumnName = "id", nullable = false)
	private NexHomeServiceCategory category;

	@Column(name = "name", nullable = false, length = 150)
	private String name;

	/** Lower-case words joined by hyphens, unique; used in URLs. */
	@Column(name = "slug", nullable = false, unique = true, length = 180)
	private String slug;

	@Column(name = "short_description", length = 300)
	private String shortDescription;

	@Column(name = "description", columnDefinition = "text")
	private String description;

	/** SERVICE_TARGET lookup code: APPLIANCE or PROPERTY; decides the pricing types allowed. */
	@Column(name = "service_target", nullable = false, length = 60)
	private String serviceTarget;

	/** PRICING_TYPE lookup code: FIXED, HOURLY (base price per hour), AREA (by home size) or INSPECTION. */
	@Column(name = "pricing_type", nullable = false, length = 60)
	private String pricingType;

	@Column(name = "base_price", nullable = false, precision = 12, scale = 2)
	private BigDecimal basePrice;

	/** What customers pay instead of the base price; null for none. At most the base price. */
	@Column(name = "discount_price", precision = 12, scale = 2)
	private BigDecimal discountPrice;

	@Column(name = "minimum_charge", nullable = false, precision = 12, scale = 2)
	private BigDecimal minimumCharge = BigDecimal.ZERO;

	@Column(name = "estimated_duration_minutes")
	private Integer estimatedDurationMinutes;

	@Column(name = "minimum_billable_minutes")
	private Integer minimumBillableMinutes;

	@Column(name = "billing_increment_minutes")
	private Integer billingIncrementMinutes;

	/** COMMISSION_TYPE lookup code: PERCENTAGE or FIXED. */
	@Column(name = "platform_commission_type", nullable = false, length = 60)
	private String platformCommissionType;

	@Column(name = "platform_commission_value", nullable = false, precision = 8, scale = 2)
	private BigDecimal platformCommissionValue = BigDecimal.ZERO;

	@Column(name = "is_instant_booking_allowed", nullable = false)
	private boolean instantBookingAllowed = true;

	@Column(name = "is_scheduled_booking_allowed", nullable = false)
	private boolean scheduledBookingAllowed = true;

	@Column(name = "is_active", nullable = false)
	private boolean active = true;

	@CreationTimestamp
	@Column(name = "creation_date", nullable = false, updatable = false)
	private Instant creationDate;

	@Column(name = "created_by", updatable = false)
	private Long createdBy;

	@UpdateTimestamp
	@Column(name = "updated_date", nullable = false)
	private Instant updatedDate;

	@Column(name = "updated_by")
	private Long updatedBy;

	@Column(name = "attribute1")
	private String attribute1;

	@Column(name = "attribute2")
	private String attribute2;

	@Column(name = "attribute3")
	private String attribute3;

	@Column(name = "attribute4")
	private String attribute4;

	@Column(name = "attribute5")
	private String attribute5;
}
