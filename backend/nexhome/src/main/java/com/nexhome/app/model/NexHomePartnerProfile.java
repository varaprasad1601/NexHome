package com.nexhome.app.model;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.annotations.UpdateTimestamp;
import org.hibernate.type.SqlTypes;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * A partner's personal details, registered address, work preferences and approval. One per account
 * ({@code user_id} is unique); the account and primary mobile number stay on {@link NexHomeUser}.
 * <p>
 * A DRAFT may be incomplete, so the columns the design marks NOT NULL are nullable here; the check constraint
 * {@code ck_nexhome_partner_profiles_submitted} requires them once the profile is submitted.
 */
@Entity
@Table(name = "nexhome_partner_profiles")
@Getter
@Setter
@NoArgsConstructor
public class NexHomePartnerProfile {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Column(name = "id")
	private Long id;

	// Generated by the database (column default), e.g. NHPART0001; never written by the application
	@Generated
	@Column(name = "public_id", nullable = false, insertable = false, updatable = false, length = 24)
	private String publicId;

	// The owner is fixed once the record is created
	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "user_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomeUser user;

	@Column(name = "first_name", nullable = false, length = 80)
	private String firstName;

	@Column(name = "middle_name", length = 80)
	private String middleName;

	@Column(name = "last_name", nullable = false, length = 80)
	private String lastName;

	/** Encrypted with {@code NexHomeFieldEncryptor}; never logged or returned unmasked. */
	@Column(name = "aadhaar_number_encrypted", columnDefinition = "text")
	private String aadhaarNumberEncrypted;

	/** Indian mobile number, different from the account's own. */
	@Column(name = "alternate_contact_number", length = 10)
	private String alternateContactNumber;

	/** Self-declared; must be true before approval. */
	@Column(name = "is_adult")
	private Boolean adult;

	/** PREFERRED_CONTACT_LANGUAGE lookup code, e.g. te. */
	@Column(name = "preferred_contact_language", length = 40)
	private String preferredContactLanguage;

	@Column(name = "address_line1", length = 300)
	private String addressLine1;

	@Column(name = "address_line2")
	private String addressLine2;

	@Column(name = "landmark")
	private String landmark;

	@Column(name = "locality", length = 100)
	private String locality;

	@Column(name = "city", length = 100)
	private String city;

	@Column(name = "state", length = 100)
	private String state;

	/** Six-digit Indian PIN code, kept as text. */
	@JdbcTypeCode(SqlTypes.CHAR)
	@Column(name = "postal_code", length = 6)
	private String postalCode;

	@Column(name = "country_code", nullable = false, length = 2)
	private String countryCode = "IN";

	@Column(name = "latitude", precision = 10, scale = 7)
	private BigDecimal latitude;

	@Column(name = "longitude", precision = 10, scale = 7)
	private BigDecimal longitude;

	/** Only staff may change it. */
	@Column(name = "registration_date", nullable = false)
	private LocalDate registrationDate;

	/** Who created the profile: a staff member, or the partner when they sign up themselves. */
	@Column(name = "registered_by", nullable = false, updatable = false)
	private Long registeredBy;

	/** SKILL_CATEGORY lookup code. */
	@Column(name = "skill_category", length = 30)
	private String skillCategory;

	@Column(name = "years_experience")
	private Short yearsExperience;

	/** The category of the partner's main skill; required once the profile leaves DRAFT. */
	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "main_service_category_id", referencedColumnName = "id")
	private NexHomeServiceCategory mainServiceCategory;

	/** A JSON array of skill codes as text, or null. */
	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "additional_skills", columnDefinition = "jsonb")
	private String additionalSkills;

	/** PREFERRED_ARRANGEMENT lookup code. */
	@Column(name = "preferred_arrangement", length = 40)
	private String preferredArrangement;

	/** PAYMENT_BASIS lookup code: the unit of the expected earnings. */
	@Column(name = "payment_basis", length = 20)
	private String paymentBasis;

	@Column(name = "expected_earnings_inr", precision = 10, scale = 2)
	private BigDecimal expectedEarningsInr;

	@Column(name = "visit_charge_inr", precision = 10, scale = 2)
	private BigDecimal visitChargeInr;

	@Column(name = "minimum_job_payment_inr", precision = 10, scale = 2)
	private BigDecimal minimumJobPaymentInr;

	@Column(name = "previous_work_details", columnDefinition = "text")
	private String previousWorkDetails;

	/** A JSON array of area codes or names as text; never null. */
	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "service_areas", nullable = false, columnDefinition = "jsonb")
	private String serviceAreas = "[]";

	@Column(name = "max_travel_km", precision = 5, scale = 1)
	private BigDecimal maxTravelKm;

	/** A JSON object of day to AVAILABILITY_SLOT codes as text, e.g. {@code {"MONDAY":["MORNING"]}}; never null. */
	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "weekly_availability", nullable = false, columnDefinition = "jsonb")
	private String weeklyAvailability = "{}";

	/** WEEKEND_AVAILABILITY lookup code. */
	@Column(name = "weekend_availability", length = 20)
	private String weekendAvailability;

	@Column(name = "emergency_contact_name", length = 120)
	private String emergencyContactName;

	/** EMERGENCY_CONTACT_RELATIONSHIP lookup code. */
	@Column(name = "emergency_contact_relationship", length = 60)
	private String emergencyContactRelationship;

	@Column(name = "emergency_contact_number", length = 10)
	private String emergencyContactNumber;

	/** The emergency contact is shown to anyone but the partner only when this is true. */
	@Column(name = "emergency_contact_permission", nullable = false)
	private boolean emergencyContactPermission = false;

	/** PARTNER_ONBOARDING_STATUS lookup code. */
	@Column(name = "onboarding_status", nullable = false, length = 60)
	private String onboardingStatus;

	/** VERIFICATION_STATUS lookup code. */
	@Column(name = "verification_status", nullable = false, length = 60)
	private String verificationStatus;

	/** PARTNER_AVAILABILITY_STATUS lookup code. */
	@Column(name = "availability_status", nullable = false, length = 60)
	private String availabilityStatus;

	@Column(name = "approved_by")
	private Long approvedBy;

	@Column(name = "approved_at")
	private Instant approvedAt;

	/** Why the profile was rejected, sent back or suspended. */
	@Column(name = "rejection_reason", columnDefinition = "text")
	private String rejectionReason;

	@CreationTimestamp
	@Column(name = "creation_date", nullable = false, updatable = false)
	private Instant creationDate;

	@Column(name = "created_by", updatable = false)
	private Long createdBy;

	@UpdateTimestamp
	@Column(name = "updated_date", nullable = false)
	private Instant updatedDate;

	@Column(name = "updated_by")
	private Long updatedBy;

	@Column(name = "attribute1")
	private String attribute1;

	@Column(name = "attribute2")
	private String attribute2;

	@Column(name = "attribute3")
	private String attribute3;

	@Column(name = "attribute4")
	private String attribute4;

	@Column(name = "attribute5")
	private String attribute5;
}
