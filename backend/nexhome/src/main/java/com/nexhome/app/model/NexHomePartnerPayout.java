package com.nexhome.app.model;

import java.math.BigDecimal;
import java.time.Instant;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * What a partner earns from one completed, paid online booking: gross less the platform's commission plus
 * adjustments (a check keeps the net consistent). One per booking.
 */
@Entity
@Table(name = "nexhome_partner_payouts")
@Getter
@Setter
@NoArgsConstructor
public class NexHomePartnerPayout {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Column(name = "id")
	private Long id;

	// Generated by the database (column default), e.g. NHPOUT0001; never written by the application
	@Generated
	@Column(name = "public_id", nullable = false, insertable = false, updatable = false, length = 24)
	private String publicId;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "partner_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomePartnerProfile partner;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "booking_id", referencedColumnName = "id", nullable = false, updatable = false)
	private NexHomeBooking booking;

	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "payment_id", referencedColumnName = "id", updatable = false)
	private NexHomePayment payment;

	@Column(name = "gross_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal grossAmount;

	@Column(name = "platform_commission", nullable = false, precision = 12, scale = 2)
	private BigDecimal platformCommission;

	@Column(name = "adjustments_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal adjustmentsAmount;

	@Column(name = "net_amount", nullable = false, precision = 12, scale = 2)
	private BigDecimal netAmount;

	@Column(name = "provider_transfer_id", length = 150)
	private String providerTransferId;

	/** PAYOUT_STATUS lookup code. */
	@Column(name = "payout_status", nullable = false, length = 60)
	private String payoutStatus;

	@Column(name = "scheduled_at")
	private Instant scheduledAt;

	@Column(name = "paid_at")
	private Instant paidAt;

	@CreationTimestamp
	@Column(name = "creation_date", nullable = false, updatable = false)
	private Instant creationDate;

	@Column(name = "created_by", updatable = false)
	private Long createdBy;

	@UpdateTimestamp
	@Column(name = "updated_date", nullable = false)
	private Instant updatedDate;

	@Column(name = "updated_by")
	private Long updatedBy;

	@Column(name = "attribute1")
	private String attribute1;

	@Column(name = "attribute2")
	private String attribute2;

	@Column(name = "attribute3")
	private String attribute3;

	@Column(name = "attribute4")
	private String attribute4;

	@Column(name = "attribute5")
	private String attribute5;
}
