-- ---------------------------------------------------------------------------------------------------------------
-- payment_orders: the gateway order for a checkout's online bookings
-- ---------------------------------------------------------------------------------------------------------------
CREATE SEQUENCE nexhome_payment_orders_public_id_seq;

CREATE TABLE nexhome_payment_orders (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id         VARCHAR(24)    NOT NULL
		DEFAULT nexhome_public_id('NHPORD', nextval('nexhome_payment_orders_public_id_seq')),
	checkout_id       UUID           NOT NULL,
	customer_id       BIGINT         NOT NULL REFERENCES nexhome_customer_profiles (id) ON DELETE RESTRICT,
	provider          VARCHAR(30)    NOT NULL,
	provider_order_id VARCHAR(150),
	amount            NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
	currency          CHAR(3)        NOT NULL DEFAULT 'INR',
	-- PAYMENT_ORDER_STATUS value code
	payment_status    VARCHAR(60)    NOT NULL,
	idempotency_key   VARCHAR(100)   NOT NULL,
	expires_at        TIMESTAMPTZ,
	creation_date     TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by        BIGINT REFERENCES nexhome_users (id),
	updated_date      TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by        BIGINT REFERENCES nexhome_users (id),
	attribute1        VARCHAR(255),
	attribute2        VARCHAR(255),
	attribute3        VARCHAR(255),
	attribute4        VARCHAR(255),
	attribute5        VARCHAR(255),
	CONSTRAINT uq_nexhome_payment_orders_public_id UNIQUE (public_id),
	CONSTRAINT uq_nexhome_payment_orders_idempotency_key UNIQUE (idempotency_key)
);

CREATE UNIQUE INDEX ux_nexhome_payment_orders_provider_order
	ON nexhome_payment_orders (provider, provider_order_id) WHERE provider_order_id IS NOT NULL;
CREATE INDEX ix_nexhome_payment_orders_checkout ON nexhome_payment_orders (checkout_id);
CREATE INDEX ix_nexhome_payment_orders_customer_created ON nexhome_payment_orders (customer_id, creation_date DESC);

-- ---------------------------------------------------------------------------------------------------------------
-- payments: what was captured for each booking of an order
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_payments (
	id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	payment_order_id    BIGINT         NOT NULL REFERENCES nexhome_payment_orders (id) ON DELETE RESTRICT,
	booking_id          BIGINT         NOT NULL REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	provider            VARCHAR(30)    NOT NULL,
	provider_payment_id VARCHAR(150),
	-- PAYMENT_METHOD and PAYMENT_STATUS value codes
	payment_method      VARCHAR(60)    NOT NULL,
	amount              NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
	currency            CHAR(3)        NOT NULL DEFAULT 'INR',
	status              VARCHAR(60)    NOT NULL,
	failure_code        VARCHAR(100),
	failure_message     TEXT,
	captured_at         TIMESTAMPTZ,
	creation_date       TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by          BIGINT REFERENCES nexhome_users (id),
	updated_date        TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by          BIGINT REFERENCES nexhome_users (id),
	attribute1          VARCHAR(255),
	attribute2          VARCHAR(255),
	attribute3          VARCHAR(255),
	attribute4          VARCHAR(255),
	attribute5          VARCHAR(255)
);

CREATE UNIQUE INDEX ux_nexhome_payments_provider_payment
	ON nexhome_payments (provider, provider_payment_id) WHERE provider_payment_id IS NOT NULL;
CREATE INDEX ix_nexhome_payments_order ON nexhome_payments (payment_order_id);
CREATE INDEX ix_nexhome_payments_booking ON nexhome_payments (booking_id);
CREATE INDEX ix_nexhome_payments_status_created ON nexhome_payments (status, creation_date);

-- ---------------------------------------------------------------------------------------------------------------
-- payment_webhook_events: the providers' events, each processed once
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_payment_webhook_events (
	id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
