-- ---------------------------------------------------------------------------------------------------------------
-- commission_rules: a service's rule beats its category's, which beats the default (neither); otherwise the
-- service's own platform commission applies
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_commission_rules (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	service_id       BIGINT REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	category_id      BIGINT REFERENCES nexhome_service_categories (id) ON DELETE RESTRICT,
	-- COMMISSION_TYPE value code
	commission_type  VARCHAR(60)  NOT NULL,
	commission_value NUMERIC(8, 2) NOT NULL CHECK (commission_value >= 0),
	valid_from       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	valid_until      TIMESTAMPTZ,
	is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
	creation_date    TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by       BIGINT REFERENCES nexhome_users (id),
	updated_date     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by       BIGINT REFERENCES nexhome_users (id),
	attribute1       VARCHAR(255),
	attribute2       VARCHAR(255),
	attribute3       VARCHAR(255),
	attribute4       VARCHAR(255),
	attribute5       VARCHAR(255),
	CONSTRAINT ck_nexhome_commission_rules_scope CHECK (service_id IS NULL OR category_id IS NULL),
	CONSTRAINT ck_nexhome_commission_rules_percentage
		CHECK (commission_type <> 'PERCENTAGE' OR commission_value <= 100),
	CONSTRAINT ck_nexhome_commission_rules_validity CHECK (valid_until IS NULL OR valid_until > valid_from)
);

CREATE INDEX ix_nexhome_commission_rules_lookup
	ON nexhome_commission_rules (is_active, service_id, category_id, valid_from);

-- ---------------------------------------------------------------------------------------------------------------
-- partner_payouts: what a partner earns from a completed, paid online booking (one row per booking)
-- ---------------------------------------------------------------------------------------------------------------
CREATE SEQUENCE nexhome_partner_payouts_public_id_seq;

CREATE TABLE nexhome_partner_payouts (
	id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id            VARCHAR(24)    NOT NULL
		DEFAULT nexhome_public_id('NHPOUT', nextval('nexhome_partner_payouts_public_id_seq')),
	partner_id           BIGINT         NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	booking_id           BIGINT         NOT NULL REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	payment_id           BIGINT REFERENCES nexhome_payments (id) ON DELETE RESTRICT,
	gross_amount         NUMERIC(12, 2) NOT NULL CHECK (gross_amount >= 0),
	platform_commission  NUMERIC(12, 2) NOT NULL CHECK (platform_commission >= 0),
	adjustments_amount   NUMERIC(12, 2) NOT NULL DEFAULT 0,
	net_amount           NUMERIC(12, 2) NOT NULL CHECK (net_amount >= 0),
	provider_transfer_id VARCHAR(150),
	-- PAYOUT_STATUS value code
	payout_status        VARCHAR(60)    NOT NULL,
	scheduled_at         TIMESTAMPTZ,
	paid_at              TIMESTAMPTZ,
	creation_date        TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by           BIGINT REFERENCES nexhome_users (id),
	updated_date         TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by           BIGINT REFERENCES nexhome_users (id),
	attribute1           VARCHAR(255),
	attribute2           VARCHAR(255),
	attribute3           VARCHAR(255),
	attribute4           VARCHAR(255),
	attribute5           VARCHAR(255),
	CONSTRAINT uq_nexhome_partner_payouts_public_id UNIQUE (public_id),
	-- One payout per booking; changes are adjustments on it
	CONSTRAINT uq_nexhome_partner_payouts_booking UNIQUE (booking_id),
	CONSTRAINT ck_nexhome_partner_payouts_net
		CHECK (net_amount = gross_amount - platform_commission + adjustments_amount),
	CONSTRAINT ck_nexhome_partner_payouts_paid CHECK (payout_status <> 'PAID' OR paid_at IS NOT NULL)
);

CREATE INDEX ix_nexhome_partner_payouts_partner_status_created
	ON nexhome_partner_payouts (partner_id, payout_status, creation_date DESC);

-- ---------------------------------------------------------------------------------------------------------------
