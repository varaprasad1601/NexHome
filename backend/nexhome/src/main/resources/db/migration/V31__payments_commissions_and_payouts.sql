FROM (VALUES ('ADMIN', 'PAYMENT_MANAGE', TRUE, TRUE, TRUE),
             ('ADMIN', 'PAYOUT_MANAGE', TRUE, TRUE, TRUE),
             ('ADMIN', 'COMMISSION_MANAGE', TRUE, TRUE, TRUE),
             ('SUB_ADMIN', 'PAYMENT_MANAGE', TRUE, FALSE, FALSE),
             ('SUB_ADMIN', 'PAYOUT_MANAGE', TRUE, FALSE, FALSE),
             ('SUB_ADMIN', 'COMMISSION_MANAGE', TRUE, FALSE, FALSE)) AS g (role_code, function_code, can_read,
                                                                          can_write, can_delete)
JOIN nexhome_roles r ON r.code = g.role_code
JOIN nexhome_functions f ON f.function_code = g.function_code;
