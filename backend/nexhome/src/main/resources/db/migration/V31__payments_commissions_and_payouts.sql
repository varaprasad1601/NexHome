CREATE INDEX ix_nexhome_partner_transfers_status_created ON nexhome_partner_transfers (status, creation_date);
CREATE INDEX ix_nexhome_partner_transfers_payout ON nexhome_partner_transfers (payout_id);

-- ---------------------------------------------------------------------------------------------------------------
-- cash_collections: cash a partner collects for a completed cash booking
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_cash_collections (
	id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	booking_id               BIGINT         NOT NULL REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	amount                   NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
	-- CASH_COLLECTION_STATUS value code
	status                   VARCHAR(60)    NOT NULL,
	collected_by             BIGINT REFERENCES nexhome_users (id),
	confirmed_at             TIMESTAMPTZ,
	customer_acknowledged_at TIMESTAMPTZ,
	notes                    TEXT,
	creation_date            TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by               BIGINT REFERENCES nexhome_users (id),
	updated_date             TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by               BIGINT REFERENCES nexhome_users (id),
	attribute1               VARCHAR(255),
	attribute2               VARCHAR(255),
	attribute3               VARCHAR(255),
	attribute4               VARCHAR(255),
	attribute5               VARCHAR(255),
	CONSTRAINT uq_nexhome_cash_collections_booking UNIQUE (booking_id),
	CONSTRAINT ck_nexhome_cash_collections_collected
		CHECK (status <> 'COLLECTED' OR (collected_by IS NOT NULL AND confirmed_at IS NOT NULL))
);

CREATE INDEX ix_nexhome_cash_collections_status_created ON nexhome_cash_collections (status, creation_date);

