-- ---------------------------------------------------------------------------------------------------------------
-- partner_manual_payouts (not in the PDF): partners are paid outside the app (PhonePe, Google Pay, Paytm, a bank
-- transfer, cash) and staff record each payment here. A partner hands the cash of cash jobs to NexHome, so NexHome
-- owes the partner every completed job (cash and online) less its commission; the recorded payouts are taken off
-- that. Replaces the wallet payouts through the payment gateway (V60's settlements stay as history).
-- ---------------------------------------------------------------------------------------------------------------
CREATE SEQUENCE nexhome_partner_manual_payouts_public_id_seq;

CREATE TABLE nexhome_partner_manual_payouts (
	id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id           VARCHAR(24)    NOT NULL
		DEFAULT nexhome_public_id('NHPPAY', nextval('nexhome_partner_manual_payouts_public_id_seq')),
	partner_id          BIGINT         NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	amount              NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
	-- PAYOUT_MODE lookup code
	payment_mode        VARCHAR(60)    NOT NULL,
	transaction_id      VARCHAR(100),
	paid_on             DATE           NOT NULL,
	notes               VARCHAR(500),
	-- RECORDED, or CANCELLED (recorded by mistake; no longer counts)
	payout_status       VARCHAR(20)    NOT NULL DEFAULT 'RECORDED',
	cancelled_at        TIMESTAMPTZ,
	cancelled_by        BIGINT REFERENCES nexhome_users (id),
	cancellation_reason VARCHAR(200),
	creation_date       TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by          BIGINT REFERENCES nexhome_users (id),
	updated_date        TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by          BIGINT REFERENCES nexhome_users (id),
	attribute1          VARCHAR(255),
	attribute2          VARCHAR(255),
	attribute3          VARCHAR(255),
	attribute4          VARCHAR(255),
	attribute5          VARCHAR(255),
	CONSTRAINT uq_nexhome_partner_manual_payouts_public_id UNIQUE (public_id),
	CONSTRAINT ck_nexhome_partner_manual_payouts_status CHECK (payout_status IN ('RECORDED', 'CANCELLED')),
	CONSTRAINT ck_nexhome_partner_manual_payouts_cancelled CHECK (
		(payout_status = 'CANCELLED') = (cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL
			AND cancellation_reason IS NOT NULL)),
	-- Every mode but cash has the payment app's or bank's transaction id
	CONSTRAINT ck_nexhome_partner_manual_payouts_transaction CHECK (
		payment_mode = 'CASH' OR transaction_id IS NOT NULL)
);

CREATE INDEX ix_nexhome_partner_manual_payouts_partner ON nexhome_partner_manual_payouts (partner_id, paid_on DESC);

-- How partners are paid
INSERT INTO nexhome_lookup_types (type_code, type_name, description, active_flag, is_system_managed, created_by,
                                  updated_by)
VALUES ('PAYOUT_MODE', 'Payout Mode', 'How NexHome paid a partner (recorded by staff).', TRUE, TRUE, 1, 1);

INSERT INTO nexhome_lookup_values (lookup_type_id, value_code, display_name, display_order, active_flag, is_default,
                                   metadata, created_by, updated_by)
SELECT t.id, v.code, v.name, v.ord, TRUE, v.code = 'PHONEPE', '{}'::jsonb, 1, 1
FROM nexhome_lookup_types t
CROSS JOIN (VALUES ('PHONEPE', 'PhonePe', 1),
                   ('GOOGLE_PAY', 'Google Pay', 2),
                   ('PAYTM', 'Paytm', 3),
                   ('OTHER_UPI', 'Other UPI', 4),
                   ('BANK_TRANSFER', 'Bank Transfer (NEFT / IMPS)', 5),
                   ('CASH', 'Cash', 6)) AS v(code, name, ord)
WHERE t.type_code = 'PAYOUT_MODE';
