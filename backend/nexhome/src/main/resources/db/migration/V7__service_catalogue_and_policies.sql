-- Module 3: service catalogue, pricing and policies (section 6). Also completes Module 2 now that the catalogue
-- exists: partner_services, and the foreign key of partner_profiles.main_service_category_id.
-- service_availability and pricing rules appear in the design's relationship map but have no table definition; they
-- are not created here.

CREATE SEQUENCE nexhome_service_categories_public_id_seq;
CREATE SEQUENCE nexhome_services_public_id_seq;
CREATE SEQUENCE nexhome_service_variants_public_id_seq;

-- ---------------------------------------------------------------------------------------------------------------
-- Categories and services
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_service_categories (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id     VARCHAR(24)  NOT NULL
		DEFAULT nexhome_public_id('NHCATG', nextval('nexhome_service_categories_public_id_seq')),
	name          VARCHAR(120) NOT NULL,
	slug          VARCHAR(150) NOT NULL,
	description   TEXT,
	icon_url      TEXT,
	display_order INTEGER      NOT NULL DEFAULT 0,
	is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
	creation_date TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255),
	CONSTRAINT uq_nexhome_service_categories_public_id UNIQUE (public_id),
	CONSTRAINT uq_nexhome_service_categories_slug UNIQUE (slug)
);

CREATE INDEX ix_nexhome_service_categories_order ON nexhome_service_categories (display_order, name) WHERE is_active;

CREATE TABLE nexhome_services (
	id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id                    VARCHAR(24)   NOT NULL
		DEFAULT nexhome_public_id('NHSERV', nextval('nexhome_services_public_id_seq')),
	category_id                  BIGINT        NOT NULL REFERENCES nexhome_service_categories (id) ON DELETE RESTRICT,
	name                         VARCHAR(150)  NOT NULL,
	slug                         VARCHAR(180)  NOT NULL,
	short_description            VARCHAR(300),
	description                  TEXT,
	-- PRICING_TYPE value code: FIXED, HOURLY (base_price per hour), PER_UNIT, INSPECTION
	pricing_type                 VARCHAR(60)   NOT NULL,
	base_price                   NUMERIC(12, 2) NOT NULL CHECK (base_price >= 0),
	minimum_charge               NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (minimum_charge >= 0),
	estimated_duration_minutes   INTEGER CHECK (estimated_duration_minutes > 0),
	minimum_billable_minutes     INTEGER CHECK (minimum_billable_minutes > 0),
	billing_increment_minutes    INTEGER CHECK (billing_increment_minutes > 0),
	-- COMMISSION_TYPE value code: PERCENTAGE or FIXED
	platform_commission_type     VARCHAR(60)   NOT NULL,
	platform_commission_value    NUMERIC(8, 2) NOT NULL DEFAULT 0 CHECK (platform_commission_value >= 0),
	is_instant_booking_allowed   BOOLEAN       NOT NULL DEFAULT TRUE,
	is_scheduled_booking_allowed BOOLEAN       NOT NULL DEFAULT TRUE,
	is_active                    BOOLEAN       NOT NULL DEFAULT TRUE,
	creation_date                TIMESTAMPTZ   NOT NULL DEFAULT now(),
	created_by                   BIGINT REFERENCES nexhome_users (id),
	updated_date                 TIMESTAMPTZ   NOT NULL DEFAULT now(),
	updated_by                   BIGINT REFERENCES nexhome_users (id),
	attribute1                   VARCHAR(255),
	attribute2                   VARCHAR(255),
	attribute3                   VARCHAR(255),
	attribute4                   VARCHAR(255),
	attribute5                   VARCHAR(255),
	CONSTRAINT uq_nexhome_services_public_id UNIQUE (public_id),
	CONSTRAINT uq_nexhome_services_slug UNIQUE (slug),
	CONSTRAINT ck_nexhome_services_commission
		CHECK (platform_commission_type <> 'PERCENTAGE' OR platform_commission_value <= 100),
	-- Hourly pricing needs a minimum and an increment to bill by
	CONSTRAINT ck_nexhome_services_hourly CHECK (pricing_type <> 'HOURLY'
		OR (minimum_billable_minutes IS NOT NULL AND billing_increment_minutes IS NOT NULL)),
	CONSTRAINT ck_nexhome_services_booking_type CHECK (is_instant_booking_allowed OR is_scheduled_booking_allowed)
);

CREATE INDEX ix_nexhome_services_category_name ON nexhome_services (category_id, name);
CREATE INDEX ix_nexhome_services_pricing_type ON nexhome_services (pricing_type) WHERE is_active;

-- ---------------------------------------------------------------------------------------------------------------
-- Service children: variants (packages), media and customer requirements
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_service_variants (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id        VARCHAR(24)   NOT NULL
		DEFAULT nexhome_public_id('NHVARI', nextval('nexhome_service_variants_public_id_seq')),
	service_id       BIGINT        NOT NULL REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	variant_code     VARCHAR(80)   NOT NULL,
	name             VARCHAR(150)  NOT NULL,
	description      TEXT,
	-- Null: the service's base price applies
	price_override   NUMERIC(12, 2) CHECK (price_override >= 0),
	-- Null: the service's estimated duration applies
	duration_minutes INTEGER CHECK (duration_minutes > 0),
	display_order    INTEGER       NOT NULL DEFAULT 0,
	is_active        BOOLEAN       NOT NULL DEFAULT TRUE,
	creation_date    TIMESTAMPTZ   NOT NULL DEFAULT now(),
	created_by       BIGINT REFERENCES nexhome_users (id),
	updated_date     TIMESTAMPTZ   NOT NULL DEFAULT now(),
	updated_by       BIGINT REFERENCES nexhome_users (id),
	attribute1       VARCHAR(255),
	attribute2       VARCHAR(255),
	attribute3       VARCHAR(255),
	attribute4       VARCHAR(255),
	attribute5       VARCHAR(255),
	CONSTRAINT uq_nexhome_service_variants_public_id UNIQUE (public_id),
	CONSTRAINT uq_nexhome_service_variants_code UNIQUE (service_id, variant_code)
);

CREATE INDEX ix_nexhome_service_variants_service_active ON nexhome_service_variants (service_id, is_active);

CREATE TABLE nexhome_service_media (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	service_id    BIGINT      NOT NULL REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	-- MEDIA_TYPE value code: IMAGE or VIDEO
	media_type    VARCHAR(60) NOT NULL,
	storage_key   TEXT        NOT NULL,
	display_order INTEGER     NOT NULL DEFAULT 0,
	is_active     BOOLEAN     NOT NULL DEFAULT TRUE,
	creation_date TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255)
);

CREATE INDEX ix_nexhome_service_media_service_order ON nexhome_service_media (service_id, display_order) WHERE is_active;

CREATE TABLE nexhome_service_requirements (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	service_id       BIGINT      NOT NULL REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	-- REQUIREMENT_TYPE value code
	requirement_type VARCHAR(30) NOT NULL,
	description      TEXT        NOT NULL,
	is_mandatory     BOOLEAN     NOT NULL DEFAULT TRUE,
	display_order    INTEGER     NOT NULL DEFAULT 0,
	creation_date    TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by       BIGINT REFERENCES nexhome_users (id),
	updated_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by       BIGINT REFERENCES nexhome_users (id),
	attribute1       VARCHAR(255),
	attribute2       VARCHAR(255),
	attribute3       VARCHAR(255),
	attribute4       VARCHAR(255),
	attribute5       VARCHAR(255)
);

CREATE INDEX ix_nexhome_service_requirements_service_order ON nexhome_service_requirements (service_id, display_order);

-- ---------------------------------------------------------------------------------------------------------------
-- FAQs: general, for one category, or for one service
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_faqs (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	question      VARCHAR(500) NOT NULL,
	answer        TEXT         NOT NULL,
	category_id   BIGINT REFERENCES nexhome_service_categories (id) ON DELETE RESTRICT,
	service_id    BIGINT REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	-- FAQ_AUDIENCE value code: CUSTOMER, PARTNER or BOTH
	audience      VARCHAR(60)  NOT NULL,
	display_order INTEGER      NOT NULL DEFAULT 0,
	is_published  BOOLEAN      NOT NULL DEFAULT FALSE,
	creation_date TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255),
	CONSTRAINT ck_nexhome_faqs_scope CHECK (category_id IS NULL OR service_id IS NULL)
);

CREATE INDEX ix_nexhome_faqs_audience_order ON nexhome_faqs (audience, display_order) WHERE is_published;
CREATE INDEX ix_nexhome_faqs_category ON nexhome_faqs (category_id);
CREATE INDEX ix_nexhome_faqs_service ON nexhome_faqs (service_id);

-- ---------------------------------------------------------------------------------------------------------------
-- Versioned policies and their acceptance. A published version never changes; a new version is a new row.
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_policy_documents (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	policy_key     VARCHAR(80)  NOT NULL,
	title          VARCHAR(200) NOT NULL,
	-- POLICY_AUDIENCE value code: CUSTOMER, PARTNER or BOTH
	audience       VARCHAR(60)  NOT NULL,
	version        VARCHAR(30)  NOT NULL,
	content        TEXT         NOT NULL,
	effective_from TIMESTAMPTZ  NOT NULL,
	published_at   TIMESTAMPTZ,
	is_published   BOOLEAN      NOT NULL DEFAULT FALSE,
	creation_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by     BIGINT REFERENCES nexhome_users (id),
	updated_date   TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by     BIGINT REFERENCES nexhome_users (id),
	attribute1     VARCHAR(255),
	attribute2     VARCHAR(255),
	attribute3     VARCHAR(255),
	attribute4     VARCHAR(255),
	attribute5     VARCHAR(255),
	CONSTRAINT uq_nexhome_policy_documents_version UNIQUE (policy_key, version),
	CONSTRAINT ck_nexhome_policy_documents_published CHECK (is_published = (published_at IS NOT NULL))
);

CREATE INDEX ix_nexhome_policy_documents_key_effective
	ON nexhome_policy_documents (policy_key, effective_from DESC) WHERE is_published;

CREATE TABLE nexhome_policy_acceptances (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id           BIGINT      NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	policy_id         BIGINT      NOT NULL REFERENCES nexhome_policy_documents (id) ON DELETE RESTRICT,
	accepted_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
	-- ACCEPTANCE_METHOD value code
	acceptance_method VARCHAR(60) NOT NULL,
	ip_address        INET,
	creation_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by        BIGINT REFERENCES nexhome_users (id),
	updated_date      TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by        BIGINT REFERENCES nexhome_users (id),
	attribute1        VARCHAR(255),
	attribute2        VARCHAR(255),
	attribute3        VARCHAR(255),
	attribute4        VARCHAR(255),
	attribute5        VARCHAR(255),
	-- Each version is its own policy row, so this keeps one acceptance per user and version
	CONSTRAINT uq_nexhome_policy_acceptances_user_policy UNIQUE (user_id, policy_id)
);

CREATE INDEX ix_nexhome_policy_acceptances_user_accepted ON nexhome_policy_acceptances (user_id, accepted_at DESC);

-- ---------------------------------------------------------------------------------------------------------------
-- Module 2 completion: the services a partner offers, and the partner's main category.
-- partner_services uses the common audit columns instead of the design's created_at / updated_at.
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_partner_services (
	id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	partner_id         BIGINT      NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	service_id         BIGINT      NOT NULL REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	experience_years   SMALLINT CHECK (experience_years BETWEEN 0 AND 60),
	is_primary_service BOOLEAN     NOT NULL DEFAULT FALSE,
	is_active          BOOLEAN     NOT NULL DEFAULT TRUE,
	creation_date      TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by         BIGINT REFERENCES nexhome_users (id),
	updated_date       TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by         BIGINT REFERENCES nexhome_users (id),
	attribute1         VARCHAR(255),
	attribute2         VARCHAR(255),
	attribute3         VARCHAR(255),
	attribute4         VARCHAR(255),
	attribute5         VARCHAR(255),
	CONSTRAINT uq_nexhome_partner_services_partner_service UNIQUE (partner_id, service_id)
);

CREATE INDEX ix_nexhome_partner_services_service_active ON nexhome_partner_services (service_id, is_active);
-- At most one primary service per partner
CREATE UNIQUE INDEX ux_nexhome_partner_services_one_primary
	ON nexhome_partner_services (partner_id) WHERE is_primary_service;

ALTER TABLE nexhome_partner_profiles
	ADD CONSTRAINT fk_nexhome_partner_profiles_main_service_category
		FOREIGN KEY (main_service_category_id) REFERENCES nexhome_service_categories (id) ON DELETE RESTRICT;
CREATE INDEX ix_nexhome_partner_profiles_main_service_category
	ON nexhome_partner_profiles (main_service_category_id);

-- The main category is now required once a profile leaves DRAFT, like the design's other NOT NULL columns
ALTER TABLE nexhome_partner_profiles DROP CONSTRAINT ck_nexhome_partner_profiles_submitted;
ALTER TABLE nexhome_partner_profiles ADD CONSTRAINT ck_nexhome_partner_profiles_submitted
	CHECK (onboarding_status = 'DRAFT' OR (
		is_adult IS NOT NULL AND preferred_contact_language IS NOT NULL AND address_line1 IS NOT NULL
		AND locality IS NOT NULL AND city IS NOT NULL AND state IS NOT NULL AND postal_code IS NOT NULL
		AND skill_category IS NOT NULL AND years_experience IS NOT NULL AND main_service_category_id IS NOT NULL
		AND preferred_arrangement IS NOT NULL AND payment_basis IS NOT NULL AND expected_earnings_inr IS NOT NULL
		AND max_travel_km IS NOT NULL AND weekend_availability IS NOT NULL AND jsonb_array_length(service_areas) > 0));

ALTER SEQUENCE nexhome_service_categories_public_id_seq OWNED BY nexhome_service_categories.public_id;
ALTER SEQUENCE nexhome_services_public_id_seq OWNED BY nexhome_services.public_id;
ALTER SEQUENCE nexhome_service_variants_public_id_seq OWNED BY nexhome_service_variants.public_id;

