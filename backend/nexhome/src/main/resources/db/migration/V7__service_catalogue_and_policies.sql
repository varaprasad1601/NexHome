INSERT INTO nexhome_role_functions (role_id, function_id, can_read, can_write, can_delete, created_by, updated_by)
SELECT r.id, f.id, g.can_read, g.can_write, g.can_delete, 1, 1
FROM (VALUES ('ADMIN', 'CATALOG_MANAGE', TRUE, TRUE, TRUE),
             ('ADMIN', 'FAQ_MANAGE', TRUE, TRUE, TRUE),
             ('ADMIN', 'POLICY_MANAGE', TRUE, TRUE, TRUE),
             ('SUB_ADMIN', 'CATALOG_MANAGE', TRUE, FALSE, FALSE),
             ('SUB_ADMIN', 'FAQ_MANAGE', TRUE, FALSE, FALSE),
             ('SUB_ADMIN', 'POLICY_MANAGE', TRUE, FALSE, FALSE)) AS g (role_code, function_code, can_read, can_write,
                                                                      can_delete)
JOIN nexhome_roles r ON r.code = g.role_code
JOIN nexhome_functions f ON f.function_code = g.function_code;
