-- Lookups (section 3) and Module 1: identity, authentication and access control (section 4).
-- Every table ends with the common audit columns (creation_date, created_by, updated_date, updated_by,
-- attribute1-attribute5). Business columns that hold a lookup value store its value_code as plain text, with no
-- foreign key to nexhome_lookup_values; the services validate the code against the lookup type.

-- ---------------------------------------------------------------------------------------------------------------
-- Users: shared account data only. Names live in the profile tables (Module 2).
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_users (
	id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	country_code          VARCHAR(5)   NOT NULL,
	mobile_number         VARCHAR(15)  NOT NULL,
	email                 VARCHAR(255),
	profile_photo_url     TEXT,
	account_status        VARCHAR(60)  NOT NULL,
	account_verified_date TIMESTAMPTZ,
	status_updated_by     BIGINT REFERENCES nexhome_users (id),
	status_updated_date   TIMESTAMPTZ,
	last_login_at         TIMESTAMPTZ,
	creation_date         TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by            BIGINT REFERENCES nexhome_users (id),
	updated_date          TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by            BIGINT REFERENCES nexhome_users (id),
	attribute1            VARCHAR(255),
	attribute2            VARCHAR(255),
	attribute3            VARCHAR(255),
	attribute4            VARCHAR(255),
	attribute5            VARCHAR(255),
	CONSTRAINT uq_nexhome_users_mobile UNIQUE (country_code, mobile_number)
);

-- Email is optional, but unique (case-insensitively) when present
CREATE UNIQUE INDEX ux_nexhome_users_email ON nexhome_users (lower(email)) WHERE email IS NOT NULL;

-- ---------------------------------------------------------------------------------------------------------------
-- Lookups: centrally managed dropdown options
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_lookup_types (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	type_code         VARCHAR(80)  NOT NULL,
	type_name         VARCHAR(120) NOT NULL,
	description       TEXT,
	active_flag       BOOLEAN      NOT NULL DEFAULT TRUE,
	is_system_managed BOOLEAN      NOT NULL DEFAULT TRUE,
	creation_date     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by        BIGINT REFERENCES nexhome_users (id),
	updated_date      TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by        BIGINT REFERENCES nexhome_users (id),
	attribute1        VARCHAR(255),
	attribute2        VARCHAR(255),
	attribute3        VARCHAR(255),
	attribute4        VARCHAR(255),
	attribute5        VARCHAR(255),
	CONSTRAINT uq_nexhome_lookup_types_code UNIQUE (type_code)
);

CREATE TABLE nexhome_lookup_values (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	lookup_type_id BIGINT       NOT NULL REFERENCES nexhome_lookup_types (id) ON DELETE RESTRICT,
	value_code     VARCHAR(80)  NOT NULL,
	display_name   VARCHAR(150) NOT NULL,
	description    TEXT,
	display_order  INTEGER      NOT NULL DEFAULT 0,
	active_flag    BOOLEAN      NOT NULL DEFAULT TRUE,
	is_default     BOOLEAN      NOT NULL DEFAULT FALSE,
	metadata       JSONB        NOT NULL DEFAULT '{}'::jsonb,
	creation_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by     BIGINT REFERENCES nexhome_users (id),
	updated_date   TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by     BIGINT REFERENCES nexhome_users (id),
	attribute1     VARCHAR(255),
	attribute2     VARCHAR(255),
	attribute3     VARCHAR(255),
	attribute4     VARCHAR(255),
	attribute5     VARCHAR(255),
	CONSTRAINT uq_nexhome_lookup_values_code UNIQUE (lookup_type_id, value_code)
);

-- At most one default value per lookup type
CREATE UNIQUE INDEX ux_nexhome_lookup_values_one_default ON nexhome_lookup_values (lookup_type_id) WHERE is_default;
CREATE INDEX ix_nexhome_lookup_values_type_active_order
	ON nexhome_lookup_values (lookup_type_id, active_flag, display_order);

-- ---------------------------------------------------------------------------------------------------------------
-- Roles and role assignment
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_roles (
	id            SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	code          VARCHAR(30) NOT NULL,
	name          VARCHAR(80) NOT NULL,
	description   TEXT,
	active_flag   BOOLEAN     NOT NULL DEFAULT TRUE,
	creation_date TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255),
	CONSTRAINT uq_nexhome_roles_code UNIQUE (code)
);

CREATE TABLE nexhome_user_roles (
	user_id       BIGINT      NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	role_id       SMALLINT    NOT NULL REFERENCES nexhome_roles (id) ON DELETE RESTRICT,
	assigned_by   BIGINT REFERENCES nexhome_users (id),
	assigned_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
	is_active     BOOLEAN     NOT NULL DEFAULT TRUE,
	creation_date TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255),
	CONSTRAINT pk_nexhome_user_roles PRIMARY KEY (user_id, role_id)
);

CREATE INDEX ix_nexhome_user_roles_role_active ON nexhome_user_roles (role_id, is_active);

-- ---------------------------------------------------------------------------------------------------------------
-- Functions and role permissions
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_functions (
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	function_module VARCHAR(50)  NOT NULL,
	function_code   VARCHAR(100) NOT NULL,
	function_name   VARCHAR(150) NOT NULL,
	function_type   VARCHAR(60)  NOT NULL,
	description     TEXT,
	active_flag     BOOLEAN      NOT NULL DEFAULT TRUE,
	creation_date   TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by      BIGINT REFERENCES nexhome_users (id),
	updated_date    TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by      BIGINT REFERENCES nexhome_users (id),
	attribute1      VARCHAR(255),
	attribute2      VARCHAR(255),
	attribute3      VARCHAR(255),
	attribute4      VARCHAR(255),
	attribute5      VARCHAR(255),
	CONSTRAINT uq_nexhome_functions_code UNIQUE (function_code)
);

CREATE INDEX ix_nexhome_functions_module_active ON nexhome_functions (function_module, active_flag);

CREATE TABLE nexhome_role_functions (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	role_id       SMALLINT    NOT NULL REFERENCES nexhome_roles (id) ON DELETE RESTRICT,
	function_id   BIGINT      NOT NULL REFERENCES nexhome_functions (id) ON DELETE RESTRICT,
	can_read      BOOLEAN     NOT NULL DEFAULT FALSE,
	can_write     BOOLEAN     NOT NULL DEFAULT FALSE,
	can_delete    BOOLEAN     NOT NULL DEFAULT FALSE,
	active_flag   BOOLEAN     NOT NULL DEFAULT TRUE,
	creation_date TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255),
	CONSTRAINT uq_nexhome_role_functions_role_function UNIQUE (role_id, function_id)
);

CREATE INDEX ix_nexhome_role_functions_role_active ON nexhome_role_functions (role_id, active_flag);
CREATE INDEX ix_nexhome_role_functions_function ON nexhome_role_functions (function_id);

-- ---------------------------------------------------------------------------------------------------------------
-- OTP requests: login, registration and phone change now; booking start/completion once bookings exist
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_auth_otp_requests (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id        BIGINT REFERENCES nexhome_users (id),
	-- The foreign key to the bookings table is added by the bookings migration
	booking_id     BIGINT,
	country_code   VARCHAR(5)  NOT NULL,
	mobile_number  VARCHAR(15) NOT NULL,
	otp_hash       TEXT        NOT NULL,
	purpose        VARCHAR(60) NOT NULL,
	request_status VARCHAR(60) NOT NULL,
	attempt_count  SMALLINT    NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
	expires_at     TIMESTAMPTZ NOT NULL,
	verified_at    TIMESTAMPTZ,
	creation_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by     BIGINT REFERENCES nexhome_users (id),
	updated_date   TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by     BIGINT REFERENCES nexhome_users (id),
	attribute1     VARCHAR(255),
	attribute2     VARCHAR(255),
	attribute3     VARCHAR(255),
	attribute4     VARCHAR(255),
	attribute5     VARCHAR(255)
);

CREATE INDEX ix_nexhome_auth_otp_requests_mobile_purpose
	ON nexhome_auth_otp_requests (country_code, mobile_number, purpose, creation_date DESC);
CREATE INDEX ix_nexhome_auth_otp_requests_expires_at ON nexhome_auth_otp_requests (expires_at);
-- At most one pending OTP per mobile number and purpose (and booking, for booking OTPs)
CREATE UNIQUE INDEX ux_nexhome_auth_otp_requests_one_pending
	ON nexhome_auth_otp_requests (country_code, mobile_number, purpose, COALESCE(booking_id, 0))
	WHERE request_status = 'PENDING';

