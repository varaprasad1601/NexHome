-- General settings (not in the PDF): one row per setting changed from its default. The keys, types, limits and
-- defaults are defined in the code (NexHomeSettingsServiceImpl.DEFINITIONS); a key without a row has its default.
CREATE TABLE nexhome_app_settings (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	setting_key   VARCHAR(80)  NOT NULL,
	setting_value TEXT         NOT NULL,
	creation_date TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255),
	CONSTRAINT uq_nexhome_app_settings_key UNIQUE (setting_key),
	CONSTRAINT ck_nexhome_app_settings_key CHECK (setting_key ~ '^[A-Z][A-Z0-9_]*$')
);

-- The online transaction fee moves from the TRANSACTION_FEE lookup (V35) to the settings, keeping its rate
INSERT INTO nexhome_app_settings (setting_key, setting_value, created_by, updated_by)
SELECT 'TRANSACTION_FEE_PERCENTAGE', lv.metadata ->> 'percentage', 1, 1
FROM nexhome_lookup_values lv
JOIN nexhome_lookup_types lt ON lt.id = lv.lookup_type_id
WHERE lt.type_code = 'TRANSACTION_FEE' AND lv.value_code = 'ONLINE' AND lv.active_flag
  AND lv.metadata ->> 'percentage' ~ '^[0-9]+(\.[0-9]+)?$';

INSERT INTO nexhome_functions (function_module, function_code, function_name, function_type, description,
                               created_by, updated_by)
VALUES ('SETTINGS', 'SETTINGS_MANAGE', 'Manage General Settings', 'FEATURE',
        'Read: the general settings (business and contact details, booking rules, staff alerts). '
            || 'Write: change them.', 1, 1);

INSERT INTO nexhome_role_functions (role_id, function_id, can_read, can_write, can_delete, created_by, updated_by)
SELECT r.id, f.id, TRUE, r.code = 'ADMIN', FALSE, 1, 1
FROM nexhome_roles r
JOIN nexhome_functions f ON f.function_code = 'SETTINGS_MANAGE'
WHERE r.code IN ('ADMIN', 'SUB_ADMIN');
