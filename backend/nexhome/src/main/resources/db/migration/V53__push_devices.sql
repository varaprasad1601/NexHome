-- Push notifications (not in the PDF): the phones of the customer and partner apps, with their Firebase Cloud
-- Messaging registration token. A token belongs to one app install, so it is unique; signing in with another account
-- on the same phone moves it to that user. NOTIFICATION_CHANNEL PUSH and DELIVERY_STATUS SENT / FAILED come from V1:
-- every push sent is a delivery log row (channel PUSH, the FCM message id).
CREATE TABLE nexhome_push_devices (
	id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id            BIGINT       NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	-- The FCM registration token of the app install
	device_token       VARCHAR(512) NOT NULL,
	-- Which app: CUSTOMER or PARTNER
	app_code           VARCHAR(20)  NOT NULL,
	-- ANDROID or IOS
	platform           VARCHAR(20)  NOT NULL,
	is_active          BOOLEAN      NOT NULL DEFAULT TRUE,
	last_seen_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	-- Why it stopped (LOGGED_OUT, UNREGISTERED: FCM no longer knows the token)
	deactivated_reason VARCHAR(40),
	creation_date      TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by         BIGINT REFERENCES nexhome_users (id),
	updated_date       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by         BIGINT REFERENCES nexhome_users (id),
	attribute1         VARCHAR(255),
	attribute2         VARCHAR(255),
	attribute3         VARCHAR(255),
	attribute4         VARCHAR(255),
	attribute5         VARCHAR(255),
	CONSTRAINT uq_nexhome_push_devices_token UNIQUE (device_token),
	CONSTRAINT ck_nexhome_push_devices_app CHECK (app_code IN ('CUSTOMER', 'PARTNER')),
	CONSTRAINT ck_nexhome_push_devices_platform CHECK (platform IN ('ANDROID', 'IOS')),
	CONSTRAINT ck_nexhome_push_devices_reason CHECK (is_active = (deactivated_reason IS NULL))
);

CREATE INDEX ix_nexhome_push_devices_user ON nexhome_push_devices (user_id) WHERE is_active;
