-- File storage (not in the PDF): every uploaded file has a row here, the bytes are in object storage (AWS S3 in
-- Mumbai, or a local folder until the account exists: nexhome.storage.provider). A file is UPLOADED, then ATTACHED
-- to what uses it (a partner document, a ticket attachment, a profile photo, a category or service image), and
-- DELETED when replaced or removed (the row stays for the history; the stored object is removed). Uploads never
-- attached are removed after a day.
CREATE SEQUENCE nexhome_files_public_id_seq;

CREATE TABLE nexhome_files (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id        VARCHAR(24)  NOT NULL
		DEFAULT nexhome_public_id('NHFILE', nextval('nexhome_files_public_id_seq')),
	-- Unguessable id in public addresses (/api/files/public/{file_uid}) and signed download links
	file_uid         UUID         NOT NULL DEFAULT gen_random_uuid(),
	-- FILE_PURPOSE code: what the file is for, which sets its types, size limit and who may see it
	purpose          VARCHAR(40)  NOT NULL,
	-- PUBLIC (images anyone may load by address) or PRIVATE (short-lived signed links after a permission check)
	visibility       VARCHAR(20)  NOT NULL,
	storage_provider VARCHAR(20)  NOT NULL,
	bucket_name      VARCHAR(100),
	storage_key      VARCHAR(500) NOT NULL,
	original_name    VARCHAR(255) NOT NULL,
	content_type     VARCHAR(100) NOT NULL,
	file_size        BIGINT       NOT NULL,
	checksum_sha256  CHAR(64)     NOT NULL,
	file_status      VARCHAR(20)  NOT NULL DEFAULT 'UPLOADED',
	-- What uses the file once ATTACHED: USER, SERVICE_CATEGORY, SERVICE_IMAGE, PARTNER_DOCUMENT, SUPPORT_ATTACHMENT
	reference_type   VARCHAR(40),
	reference_id     BIGINT,
	attached_at      TIMESTAMPTZ,
	deleted_at       TIMESTAMPTZ,
	deleted_by       BIGINT REFERENCES nexhome_users (id),
	creation_date    TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by       BIGINT REFERENCES nexhome_users (id),
	updated_date     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by       BIGINT REFERENCES nexhome_users (id),
	attribute1       VARCHAR(255),
	attribute2       VARCHAR(255),
	attribute3       VARCHAR(255),
	attribute4       VARCHAR(255),
	attribute5       VARCHAR(255),
	CONSTRAINT uq_nexhome_files_public_id UNIQUE (public_id),
	CONSTRAINT uq_nexhome_files_file_uid UNIQUE (file_uid),
	CONSTRAINT uq_nexhome_files_storage_key UNIQUE (storage_provider, storage_key),
	CONSTRAINT ck_nexhome_files_purpose CHECK (purpose IN ('PROFILE_PHOTO', 'CATEGORY_IMAGE', 'SERVICE_IMAGE',
		'PARTNER_DOCUMENT', 'SUPPORT_ATTACHMENT')),
	CONSTRAINT ck_nexhome_files_visibility CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
	CONSTRAINT ck_nexhome_files_status CHECK (file_status IN ('UPLOADED', 'ATTACHED', 'DELETED')),
	CONSTRAINT ck_nexhome_files_size CHECK (file_size > 0),
	CONSTRAINT ck_nexhome_files_reference CHECK ((reference_type IS NULL) = (reference_id IS NULL)),
	CONSTRAINT ck_nexhome_files_attached CHECK (file_status <> 'ATTACHED'
		OR (reference_type IS NOT NULL AND attached_at IS NOT NULL)),
	CONSTRAINT ck_nexhome_files_deleted CHECK ((file_status = 'DELETED') = (deleted_at IS NOT NULL))
);

-- What a record uses, and the cleanup of uploads never attached
CREATE INDEX ix_nexhome_files_reference ON nexhome_files (reference_type, reference_id) WHERE file_status = 'ATTACHED';
CREATE INDEX ix_nexhome_files_unattached ON nexhome_files (creation_date) WHERE file_status = 'UPLOADED';

-- The records that use files point to them
ALTER TABLE nexhome_partner_documents
	ADD COLUMN file_id BIGINT REFERENCES nexhome_files (id) ON DELETE RESTRICT;
ALTER TABLE nexhome_support_ticket_attachments
	ADD COLUMN file_id BIGINT REFERENCES nexhome_files (id) ON DELETE RESTRICT;

-- Service images move from the database to storage: the application copies each image's bytes to storage at
-- startup and then clears image_data, so an image has its bytes in exactly one place
ALTER TABLE nexhome_service_images
	ADD COLUMN file_id BIGINT REFERENCES nexhome_files (id) ON DELETE RESTRICT,
	ALTER COLUMN image_data DROP NOT NULL,
	ADD CONSTRAINT ck_nexhome_service_images_bytes CHECK ((file_id IS NULL) <> (image_data IS NULL));

