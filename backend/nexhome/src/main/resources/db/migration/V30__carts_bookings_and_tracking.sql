-- ---------------------------------------------------------------------------------------------------------------
-- Module 6: cart, bookings and tracking. The lookups (CART_STATUS, BOOKING_TYPE, BOOKING_STATUS,
-- BOOKING_PAYMENT_STATUS, PAYMENT_METHOD, ASSIGNMENT_STATUS, BOOKING_TIMER_EVENT) are seeded by V1.
--
-- Variants are referenced ON DELETE SET NULL: the catalogue's service form replaces variant lists, and a booking keeps
-- its own name and price snapshots. Addresses are RESTRICT: an address used by a booking is not deleted.
-- ---------------------------------------------------------------------------------------------------------------

-- ---------------------------------------------------------------------------------------------------------------
-- carts / cart_items
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_carts (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	customer_id   BIGINT      NOT NULL REFERENCES nexhome_customer_profiles (id) ON DELETE RESTRICT,
	-- CART_STATUS value code
	status        VARCHAR(60) NOT NULL,
	creation_date TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255)
);

-- One active cart per customer
CREATE UNIQUE INDEX ux_nexhome_carts_one_active ON nexhome_carts (customer_id) WHERE status = 'ACTIVE';

CREATE TABLE nexhome_cart_items (
	id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	cart_id              BIGINT        NOT NULL REFERENCES nexhome_carts (id) ON DELETE CASCADE,
	service_id           BIGINT        NOT NULL REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	variant_id           BIGINT REFERENCES nexhome_service_variants (id) ON DELETE CASCADE,
	-- Informational only: checkout prices again on the server
	estimated_unit_price NUMERIC(12, 2) NOT NULL CHECK (estimated_unit_price >= 0),
	creation_date        TIMESTAMPTZ   NOT NULL DEFAULT now(),
	created_by           BIGINT REFERENCES nexhome_users (id),
	updated_date         TIMESTAMPTZ   NOT NULL DEFAULT now(),
	updated_by           BIGINT REFERENCES nexhome_users (id),
	attribute1           VARCHAR(255),
	attribute2           VARCHAR(255),
	attribute3           VARCHAR(255),
	attribute4           VARCHAR(255),
	attribute5           VARCHAR(255)
);

CREATE INDEX ix_nexhome_cart_items_cart ON nexhome_cart_items (cart_id);

-- ---------------------------------------------------------------------------------------------------------------
-- bookings: the service transaction, with snapshots that survive catalogue and address changes
-- ---------------------------------------------------------------------------------------------------------------
CREATE SEQUENCE nexhome_bookings_public_id_seq;

CREATE TABLE nexhome_bookings (
	id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id             VARCHAR(24)    NOT NULL
		DEFAULT nexhome_public_id('NHBOOK', nextval('nexhome_bookings_public_id_seq')),
	-- Groups the bookings of one checkout
	checkout_id           UUID,
	customer_id           BIGINT         NOT NULL REFERENCES nexhome_customer_profiles (id) ON DELETE RESTRICT,
	service_id            BIGINT         NOT NULL REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	variant_id            BIGINT REFERENCES nexhome_service_variants (id) ON DELETE SET NULL,
	partner_id            BIGINT REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	address_id            BIGINT         NOT NULL REFERENCES nexhome_addresses (id) ON DELETE RESTRICT,
	-- BOOKING_TYPE, BOOKING_STATUS, BOOKING_PAYMENT_STATUS, PAYMENT_METHOD value codes
	booking_type          VARCHAR(60)    NOT NULL,
	booking_status        VARCHAR(60)    NOT NULL,
	payment_status        VARCHAR(60)    NOT NULL,
	payment_method        VARCHAR(60)    NOT NULL,
	scheduled_start_at    TIMESTAMPTZ    NOT NULL,
	scheduled_end_at      TIMESTAMPTZ,
	actual_start_at       TIMESTAMPTZ,
	actual_end_at         TIMESTAMPTZ,
	service_name_snapshot VARCHAR(150)   NOT NULL,
	address_snapshot      JSONB          NOT NULL,
	pricing_snapshot      JSONB          NOT NULL,
	subtotal_amount       NUMERIC(12, 2) NOT NULL CHECK (subtotal_amount >= 0),
	discount_amount       NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
	tax_amount            NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
	total_amount          NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
	currency              CHAR(3)        NOT NULL DEFAULT 'INR',
	cancellation_reason   TEXT,
	creation_date         TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by            BIGINT REFERENCES nexhome_users (id),
	updated_date          TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by            BIGINT REFERENCES nexhome_users (id),
	attribute1            VARCHAR(255),
	attribute2            VARCHAR(255),
	attribute3            VARCHAR(255),
	attribute4            VARCHAR(255),
	attribute5            VARCHAR(255),
	CONSTRAINT uq_nexhome_bookings_public_id UNIQUE (public_id),
	CONSTRAINT ck_nexhome_bookings_scheduled_end CHECK (scheduled_end_at IS NULL OR scheduled_end_at > scheduled_start_at),
	CONSTRAINT ck_nexhome_bookings_actual_end
		CHECK (actual_end_at IS NULL OR (actual_start_at IS NOT NULL AND actual_end_at >= actual_start_at)),
	-- Assigned and later stages name the partner
	CONSTRAINT ck_nexhome_bookings_partner
		CHECK (booking_status NOT IN ('ASSIGNED', 'PARTNER_EN_ROUTE', 'IN_PROGRESS', 'PAUSED', 'COMPLETED')
			OR partner_id IS NOT NULL),
	CONSTRAINT ck_nexhome_bookings_cancellation_reason
		CHECK (booking_status <> 'CANCELLED' OR cancellation_reason IS NOT NULL)
);

CREATE INDEX ix_nexhome_bookings_customer_created ON nexhome_bookings (customer_id, creation_date DESC);
CREATE INDEX ix_nexhome_bookings_partner_status_start
	ON nexhome_bookings (partner_id, booking_status, scheduled_start_at);
CREATE INDEX ix_nexhome_bookings_status_created ON nexhome_bookings (booking_status, creation_date);
CREATE INDEX ix_nexhome_bookings_checkout ON nexhome_bookings (checkout_id);
CREATE INDEX ix_nexhome_bookings_scheduled_start ON nexhome_bookings (scheduled_start_at);
CREATE INDEX ix_nexhome_bookings_address ON nexhome_bookings (address_id);

-- ---------------------------------------------------------------------------------------------------------------
-- booking_items: line items with price snapshots
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_booking_items (
	id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	booking_id         BIGINT         NOT NULL REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	service_id         BIGINT         NOT NULL REFERENCES nexhome_services (id) ON DELETE RESTRICT,
	variant_id         BIGINT REFERENCES nexhome_service_variants (id) ON DELETE SET NULL,
	item_name_snapshot VARCHAR(150)   NOT NULL,
	unit_price         NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
	line_total         NUMERIC(12, 2) NOT NULL CHECK (line_total >= 0),
	creation_date      TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by         BIGINT REFERENCES nexhome_users (id),
	updated_date       TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by         BIGINT REFERENCES nexhome_users (id),
	attribute1         VARCHAR(255),
	attribute2         VARCHAR(255),
	attribute3         VARCHAR(255),
	attribute4         VARCHAR(255),
	attribute5         VARCHAR(255)
);

CREATE INDEX ix_nexhome_booking_items_booking ON nexhome_booking_items (booking_id);

-- ---------------------------------------------------------------------------------------------------------------
-- booking_status_history: every status change, written with the booking update
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_booking_status_history (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	booking_id    BIGINT      NOT NULL REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	old_status    VARCHAR(60),
	new_status    VARCHAR(60) NOT NULL,
	changed_by    BIGINT REFERENCES nexhome_users (id),
	reason        TEXT,
	creation_date TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255)
);

CREATE INDEX ix_nexhome_booking_status_history_booking ON nexhome_booking_status_history (booking_id, creation_date);

-- ---------------------------------------------------------------------------------------------------------------
-- booking_assignments: offers to partners and their answers
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_booking_assignments (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	booking_id        BIGINT      NOT NULL REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	partner_id        BIGINT      NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	assigned_by       BIGINT REFERENCES nexhome_users (id),
	-- ASSIGNMENT_STATUS value code
	assignment_status VARCHAR(60) NOT NULL,
	offered_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
	responded_at      TIMESTAMPTZ,
	expires_at        TIMESTAMPTZ,
	rejection_reason  TEXT,
	creation_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by        BIGINT REFERENCES nexhome_users (id),
	updated_date      TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by        BIGINT REFERENCES nexhome_users (id),
	attribute1        VARCHAR(255),
	attribute2        VARCHAR(255),
	attribute3        VARCHAR(255),
	attribute4        VARCHAR(255),
	attribute5        VARCHAR(255),
	CONSTRAINT ck_nexhome_booking_assignments_rejection
		CHECK (assignment_status <> 'REJECTED' OR rejection_reason IS NOT NULL)
);

CREATE INDEX ix_nexhome_booking_assignments_partner_status ON nexhome_booking_assignments (partner_id, assignment_status);
CREATE INDEX ix_nexhome_booking_assignments_booking ON nexhome_booking_assignments (booking_id);
-- One accepted (or done) assignment per booking
CREATE UNIQUE INDEX ux_nexhome_booking_assignments_one_accepted
	ON nexhome_booking_assignments (booking_id) WHERE assignment_status IN ('ACCEPTED', 'COMPLETED');

-- ---------------------------------------------------------------------------------------------------------------
-- booking_time_logs: the service timer
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_booking_time_logs (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	booking_id    BIGINT      NOT NULL REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	-- BOOKING_TIMER_EVENT value code
	event_type    VARCHAR(60) NOT NULL,
	event_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
	recorded_by   BIGINT REFERENCES nexhome_users (id),
	notes         TEXT,
	creation_date TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255)
);

CREATE INDEX ix_nexhome_booking_time_logs_booking ON nexhome_booking_time_logs (booking_id, event_at);

-- ---------------------------------------------------------------------------------------------------------------
-- partner_location_updates: live tracking, visible to the booking's customer, its partner and staff
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_partner_location_updates (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	partner_id    BIGINT        NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	booking_id    BIGINT REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	latitude      NUMERIC(10, 7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
	longitude     NUMERIC(10, 7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
	recorded_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
	creation_date TIMESTAMPTZ   NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ   NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255)
);

CREATE INDEX ix_nexhome_partner_location_updates_partner_booking
	ON nexhome_partner_location_updates (partner_id, booking_id, recorded_at DESC);

-- Slot reservations now point at real bookings (V29 left the foreign key for this module)
ALTER TABLE nexhome_partner_slot_reservations
	ADD CONSTRAINT fk_nexhome_partner_slot_reservations_booking
		FOREIGN KEY (booking_id) REFERENCES nexhome_bookings (id) ON DELETE RESTRICT;

-- ---------------------------------------------------------------------------------------------------------------
-- Function: Manage Bookings (all bookings, creating them for customers, statuses, assignment, the timer)
-- ---------------------------------------------------------------------------------------------------------------
INSERT INTO nexhome_functions (function_module, function_code, function_name, function_type, description,
                               created_by, updated_by)
VALUES ('BOOKINGS', 'BOOKING_MANAGE', 'Manage Bookings', 'FEATURE',
        'Read: every booking with its history, assignments, timer and location. Write: create bookings for '
            || 'customers, confirm, cancel, assign partners and run the service timer on a partner''s behalf.', 1, 1);

INSERT INTO nexhome_role_functions (role_id, function_id, can_read, can_write, can_delete, created_by, updated_by)
SELECT r.id, f.id, g.can_read, g.can_write, g.can_delete, 1, 1
FROM (VALUES ('ADMIN', TRUE, TRUE, TRUE),
             ('SUB_ADMIN', TRUE, TRUE, FALSE)) AS g (role_code, can_read, can_write, can_delete)
JOIN nexhome_roles r ON r.code = g.role_code
JOIN nexhome_functions f ON f.function_code = 'BOOKING_MANAGE';
