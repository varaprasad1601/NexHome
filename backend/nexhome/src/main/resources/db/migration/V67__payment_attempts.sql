-- Every attempt to pay a payment order at the gateway (not in the PDF): successful, failed, pending, cancelled or
-- dropped, as the gateway lists them (Cashfree's /orders/{id}/payments), kept when the order is checked
-- (POST /api/payments/orders/verify, /orders/sync) and when a payment is captured. The console's order page lists
-- them like the gateway's dashboard; each new or changed attempt also shows in its bookings' history.
CREATE TABLE nexhome_payment_attempts (
	id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	payment_order_id      BIGINT         NOT NULL REFERENCES nexhome_payment_orders (id) ON DELETE RESTRICT,
	provider              VARCHAR(30)    NOT NULL,
	-- the gateway's id of the attempt (Cashfree's cf_payment_id; MANUAL: the recorded reference)
	provider_payment_id   VARCHAR(150)   NOT NULL,
	-- SUCCESS, FAILED, PENDING, USER_DROPPED, CANCELLED, VOID, NOT_ATTEMPTED (the gateway's own words)
	attempt_status        VARCHAR(40)    NOT NULL,
	-- the gateway's payment group (upi, credit_card, net_banking, ...) and what was used (UPI id, card, bank)
	payment_mode          VARCHAR(40),
	payment_method_detail VARCHAR(200),
	amount                NUMERIC(12, 2),
	currency              CHAR(3)        NOT NULL DEFAULT 'INR',
	bank_reference        VARCHAR(150),
	error_code            VARCHAR(100),
	message               TEXT,
	attempted_at          TIMESTAMPTZ,
	completed_at          TIMESTAMPTZ,
	creation_date         TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by            BIGINT REFERENCES nexhome_users (id),
	updated_date          TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by            BIGINT REFERENCES nexhome_users (id),
	attribute1            VARCHAR(255),
	attribute2            VARCHAR(255),
	attribute3            VARCHAR(255),
	attribute4            VARCHAR(255),
	attribute5            VARCHAR(255),
	CONSTRAINT ux_nexhome_payment_attempts_provider_payment UNIQUE (provider, provider_payment_id)
);

CREATE INDEX ix_nexhome_payment_attempts_order ON nexhome_payment_attempts (payment_order_id);
