-- ---------------------------------------------------------------------------------------------------------------
-- Module 5: availability and slots. A partner's weekly working hours stay the slot grid of
-- nexhome_partner_profiles.weekly_availability (AVAILABILITY_SLOT codes per day, V6/V22); the design's
-- partner_availability table is not created. Added here: time off (leave and other unavailable periods) and slot
-- reservations (time held for, or confirmed to, a booking), which may never overlap for one partner.
-- ---------------------------------------------------------------------------------------------------------------

-- Exclusion constraints on (partner, time range) need the btree_gist operator classes
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- SLOT_RESERVATION_STATUS (HELD, CONFIRMED, RELEASED, EXPIRED, COMPLETED) is seeded by V1

-- ---------------------------------------------------------------------------------------------------------------
-- partner_time_off: leave and unavailable periods
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_partner_time_off (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	partner_id    BIGINT       NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	starts_at     TIMESTAMPTZ  NOT NULL,
	ends_at       TIMESTAMPTZ  NOT NULL,
	reason        VARCHAR(200),
	creation_date TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255),
	CONSTRAINT ck_nexhome_partner_time_off_range CHECK (ends_at > starts_at),
	-- One partner's periods of time off never overlap (edit the existing one instead)
	CONSTRAINT ex_nexhome_partner_time_off_overlap
		EXCLUDE USING gist (partner_id WITH =, tstzrange(starts_at, ends_at) WITH &&)
);

CREATE INDEX ix_nexhome_partner_time_off_partner_range ON nexhome_partner_time_off (partner_id, starts_at, ends_at);

-- ---------------------------------------------------------------------------------------------------------------
-- partner_slot_reservations: held / confirmed booking slots
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_partner_slot_reservations (
	id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	partner_id         BIGINT      NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	-- The booking it is held for; the foreign key comes with the bookings table (Module 6)
	booking_id         BIGINT,
	starts_at          TIMESTAMPTZ NOT NULL,
	ends_at            TIMESTAMPTZ NOT NULL,
	-- SLOT_RESERVATION_STATUS value code
	reservation_status VARCHAR(60) NOT NULL,
	hold_expires_at    TIMESTAMPTZ,
	creation_date      TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by         BIGINT REFERENCES nexhome_users (id),
	updated_date       TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by         BIGINT REFERENCES nexhome_users (id),
	attribute1         VARCHAR(255),
	attribute2         VARCHAR(255),
	attribute3         VARCHAR(255),
	attribute4         VARCHAR(255),
	attribute5         VARCHAR(255),
	CONSTRAINT ck_nexhome_partner_slot_reservations_range CHECK (ends_at > starts_at),
	-- A hold runs out; nothing else does
	CONSTRAINT ck_nexhome_partner_slot_reservations_hold
		CHECK (reservation_status <> 'HELD' OR hold_expires_at IS NOT NULL),
	-- A partner is never held or booked twice at the same time
	CONSTRAINT ex_nexhome_partner_slot_reservations_overlap
		EXCLUDE USING gist (partner_id WITH =, tstzrange(starts_at, ends_at) WITH &&)
		WHERE (reservation_status IN ('HELD', 'CONFIRMED'))
);

CREATE INDEX ix_nexhome_partner_slot_reservations_status_start
	ON nexhome_partner_slot_reservations (reservation_status, starts_at);
CREATE INDEX ix_nexhome_partner_slot_reservations_partner_start
	ON nexhome_partner_slot_reservations (partner_id, starts_at);
CREATE INDEX ix_nexhome_partner_slot_reservations_booking ON nexhome_partner_slot_reservations (booking_id);

