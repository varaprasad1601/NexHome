JOIN nexhome_lookup_types lt ON lt.type_code = v.type_code;

-- The default support priority
UPDATE nexhome_lookup_values lv
SET is_default = TRUE
FROM nexhome_lookup_types lt
WHERE lt.id = lv.lookup_type_id AND lt.type_code = 'SUPPORT_PRIORITY' AND lv.value_code = 'MEDIUM'
	AND NOT EXISTS (SELECT 1 FROM nexhome_lookup_values d WHERE d.lookup_type_id = lt.id AND d.is_default);

