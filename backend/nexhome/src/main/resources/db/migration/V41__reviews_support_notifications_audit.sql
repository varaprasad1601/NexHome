-- Module 9: reviews, support, notifications and audit (PDF section 12). Lookups REVIEW_STATUS, SUPPORT_PRIORITY,
-- SUPPORT_TICKET_STATUS, NOTIFICATION_CHANNEL and DELIVERY_STATUS come from V1; this adds SUPPORT_CATEGORY and
-- NOTIFICATION_TYPE (the PDF suggests lookups for both) and the IN_APP channel (no push, SMS or email provider exists
-- yet: notifications are delivered in the app, logged as such).

-- ---------------------------------------------------------------------------------------------------------------
-- booking_reviews: a customer's rating of a completed booking, one per booking
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_booking_reviews (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	booking_id     BIGINT      NOT NULL REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	customer_id    BIGINT      NOT NULL REFERENCES nexhome_customer_profiles (id) ON DELETE RESTRICT,
	partner_id     BIGINT      NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	service_rating SMALLINT    NOT NULL CHECK (service_rating BETWEEN 1 AND 5),
	partner_rating SMALLINT    NOT NULL CHECK (partner_rating BETWEEN 1 AND 5),
	review_text    TEXT,
	-- REVIEW_STATUS value code
	review_status  VARCHAR(60) NOT NULL,
	creation_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by     BIGINT REFERENCES nexhome_users (id),
	updated_date   TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by     BIGINT REFERENCES nexhome_users (id),
	attribute1     VARCHAR(255),
	attribute2     VARCHAR(255),
	attribute3     VARCHAR(255),
	attribute4     VARCHAR(255),
	attribute5     VARCHAR(255),
	CONSTRAINT uq_nexhome_booking_reviews_booking UNIQUE (booking_id)
);

CREATE INDEX ix_nexhome_booking_reviews_partner_rating ON nexhome_booking_reviews (partner_id, partner_rating);
CREATE INDEX ix_nexhome_booking_reviews_service_rating ON nexhome_booking_reviews (service_rating);
CREATE INDEX ix_nexhome_booking_reviews_customer ON nexhome_booking_reviews (customer_id);

-- ---------------------------------------------------------------------------------------------------------------
-- support_tickets, messages and attachments
-- ---------------------------------------------------------------------------------------------------------------
CREATE SEQUENCE nexhome_support_tickets_public_id_seq;

CREATE TABLE nexhome_support_tickets (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id     VARCHAR(24)  NOT NULL
		DEFAULT nexhome_public_id('NHTICK', nextval('nexhome_support_tickets_public_id_seq')),
	-- The ticket's owner (created_by is whoever opened it, e.g. staff on the requester's behalf)
	requester_id  BIGINT       NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	booking_id    BIGINT REFERENCES nexhome_bookings (id) ON DELETE RESTRICT,
	payment_id    BIGINT REFERENCES nexhome_payments (id) ON DELETE RESTRICT,
	-- SUPPORT_CATEGORY, SUPPORT_PRIORITY and SUPPORT_TICKET_STATUS value codes
	category      VARCHAR(40)  NOT NULL,
	subject       VARCHAR(200) NOT NULL,
	description   TEXT         NOT NULL,
	priority      VARCHAR(60)  NOT NULL,
	status        VARCHAR(60)  NOT NULL,
	assigned_to   BIGINT REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	resolved_at   TIMESTAMPTZ,
	closed_at     TIMESTAMPTZ,
	creation_date TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255),
	CONSTRAINT uq_nexhome_support_tickets_public_id UNIQUE (public_id),
	-- A resolved or closed ticket says when
	CONSTRAINT ck_nexhome_support_tickets_resolved CHECK (status <> 'RESOLVED' OR resolved_at IS NOT NULL),
	CONSTRAINT ck_nexhome_support_tickets_closed CHECK (status <> 'CLOSED' OR closed_at IS NOT NULL)
);

CREATE INDEX ix_nexhome_support_tickets_status ON nexhome_support_tickets (status, priority, creation_date);
CREATE INDEX ix_nexhome_support_tickets_booking ON nexhome_support_tickets (booking_id);
CREATE INDEX ix_nexhome_support_tickets_requester ON nexhome_support_tickets (requester_id, creation_date DESC);
CREATE INDEX ix_nexhome_support_tickets_assigned ON nexhome_support_tickets (assigned_to);

CREATE TABLE nexhome_support_ticket_messages (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ticket_id        BIGINT      NOT NULL REFERENCES nexhome_support_tickets (id) ON DELETE RESTRICT,
	sender_id        BIGINT      NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	message          TEXT        NOT NULL,
	-- Staff only: never shown to the requester
	is_internal_note BOOLEAN     NOT NULL DEFAULT FALSE,
	creation_date    TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by       BIGINT REFERENCES nexhome_users (id),
	updated_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by       BIGINT REFERENCES nexhome_users (id),
	attribute1       VARCHAR(255),
	attribute2       VARCHAR(255),
	attribute3       VARCHAR(255),
	attribute4       VARCHAR(255),
	attribute5       VARCHAR(255)
);

CREATE INDEX ix_nexhome_support_ticket_messages_ticket ON nexhome_support_ticket_messages (ticket_id, creation_date);

CREATE TABLE nexhome_support_ticket_attachments (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ticket_id     BIGINT       NOT NULL REFERENCES nexhome_support_tickets (id) ON DELETE RESTRICT,
	message_id    BIGINT REFERENCES nexhome_support_ticket_messages (id) ON DELETE RESTRICT,
	-- The file's key in private object storage (none exists yet: the client supplies it, as for partner documents)
	storage_key   TEXT         NOT NULL,
	file_type     VARCHAR(100) NOT NULL,
	creation_date TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255)
);

CREATE INDEX ix_nexhome_support_ticket_attachments_ticket ON nexhome_support_ticket_attachments (ticket_id);

-- ---------------------------------------------------------------------------------------------------------------
-- notifications and their delivery logs
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_notifications (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id           BIGINT       NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	-- NOTIFICATION_TYPE value code
	notification_type VARCHAR(50)  NOT NULL,
	title             VARCHAR(200) NOT NULL,
	message           TEXT         NOT NULL,
	-- What it is about, e.g. BOOKING + the booking id (checked by the service that sends it)
	reference_type    VARCHAR(40),
	reference_id      BIGINT,
	read_at           TIMESTAMPTZ,
	creation_date     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by        BIGINT REFERENCES nexhome_users (id),
	updated_date      TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by        BIGINT REFERENCES nexhome_users (id),
	attribute1        VARCHAR(255),
	attribute2        VARCHAR(255),
	attribute3        VARCHAR(255),
	attribute4        VARCHAR(255),
	attribute5        VARCHAR(255),
	CONSTRAINT ck_nexhome_notifications_reference CHECK ((reference_type IS NULL) = (reference_id IS NULL))
);

CREATE INDEX ix_nexhome_notifications_user ON nexhome_notifications (user_id, creation_date DESC);
CREATE INDEX ix_nexhome_notifications_unread ON nexhome_notifications (user_id) WHERE read_at IS NULL;

CREATE TABLE nexhome_notification_delivery_logs (
	id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	-- Kept when the user deletes the notification
	notification_id     BIGINT REFERENCES nexhome_notifications (id) ON DELETE SET NULL,
	user_id             BIGINT       NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	-- NOTIFICATION_CHANNEL and DELIVERY_STATUS value codes
	channel             VARCHAR(60)  NOT NULL,
	provider_message_id VARCHAR(150),
	delivery_status     VARCHAR(60)  NOT NULL,
	sent_at             TIMESTAMPTZ,
	delivered_at        TIMESTAMPTZ,
	failure_reason      TEXT,
	creation_date       TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by          BIGINT REFERENCES nexhome_users (id),
	updated_date        TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by          BIGINT REFERENCES nexhome_users (id),
	attribute1          VARCHAR(255),
	attribute2          VARCHAR(255),
	attribute3          VARCHAR(255),
	attribute4          VARCHAR(255),
	attribute5          VARCHAR(255)
);

CREATE INDEX ix_nexhome_notification_delivery_logs_status ON nexhome_notification_delivery_logs (delivery_status,
	sent_at);
CREATE INDEX ix_nexhome_notification_delivery_logs_notification ON nexhome_notification_delivery_logs (notification_id);

-- ---------------------------------------------------------------------------------------------------------------
-- audit_logs: security and business history (never OTPs, tokens, bank details or document contents)
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_audit_logs (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	actor_user_id BIGINT REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	action        VARCHAR(100) NOT NULL,
	entity_type   VARCHAR(60)  NOT NULL,
	entity_id     VARCHAR(100) NOT NULL,
	old_values    JSONB,
	new_values    JSONB,
	ip_address    INET,
	creation_date TIMESTAMPTZ  NOT NULL DEFAULT now(),
	created_by    BIGINT REFERENCES nexhome_users (id),
	updated_date  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_by    BIGINT REFERENCES nexhome_users (id),
	attribute1    VARCHAR(255),
	attribute2    VARCHAR(255),
	attribute3    VARCHAR(255),
	attribute4    VARCHAR(255),
	attribute5    VARCHAR(255)
);

CREATE INDEX ix_nexhome_audit_logs_entity ON nexhome_audit_logs (entity_type, entity_id, creation_date DESC);
CREATE INDEX ix_nexhome_audit_logs_actor ON nexhome_audit_logs (actor_user_id, creation_date DESC);
CREATE INDEX ix_nexhome_audit_logs_created ON nexhome_audit_logs (creation_date DESC);

