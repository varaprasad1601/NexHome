             ('SUPPORT_CATEGORY', 'OTHER', 'Other', 7),
             ('NOTIFICATION_TYPE', 'BOOKING', 'Booking', 1),
             ('NOTIFICATION_TYPE', 'PAYMENT', 'Payment', 2),
             ('NOTIFICATION_TYPE', 'REVIEW', 'Review', 3),
             ('NOTIFICATION_TYPE', 'SUPPORT', 'Support', 4),
