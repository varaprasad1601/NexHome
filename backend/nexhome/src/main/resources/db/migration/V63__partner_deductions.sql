-- ---------------------------------------------------------------------------------------------------------------
-- partner_deductions (not in the PDF): an amount NexHome keeps from what it owes a partner and never pays (a penalty,
-- damage, a customer complaint, recovering an advance). Recorded by staff with a reason, on its own or with a payout
-- (then linked to it); what NexHome owes = earned - payouts - deductions. Cancelled (with a reason), never deleted.
-- ---------------------------------------------------------------------------------------------------------------
CREATE SEQUENCE nexhome_partner_deductions_public_id_seq;

CREATE TABLE nexhome_partner_deductions (
	id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id           VARCHAR(24)    NOT NULL
		DEFAULT nexhome_public_id('NHPDED', nextval('nexhome_partner_deductions_public_id_seq')),
	partner_id          BIGINT         NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	-- The payout it was recorded with, if any
	payout_id           BIGINT REFERENCES nexhome_partner_manual_payouts (id) ON DELETE RESTRICT,
	amount              NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
	-- DEDUCTION_REASON lookup code
	deduction_reason    VARCHAR(60)    NOT NULL,
	notes               VARCHAR(500),
	deducted_on         DATE           NOT NULL,
	-- RECORDED, or CANCELLED (recorded by mistake; no longer counts)
	deduction_status    VARCHAR(20)    NOT NULL DEFAULT 'RECORDED',
	cancelled_at        TIMESTAMPTZ,
	cancelled_by        BIGINT REFERENCES nexhome_users (id),
	cancellation_reason VARCHAR(200),
	creation_date       TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by          BIGINT REFERENCES nexhome_users (id),
	updated_date        TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by          BIGINT REFERENCES nexhome_users (id),
	attribute1          VARCHAR(255),
	attribute2          VARCHAR(255),
	attribute3          VARCHAR(255),
	attribute4          VARCHAR(255),
	attribute5          VARCHAR(255),
	CONSTRAINT uq_nexhome_partner_deductions_public_id UNIQUE (public_id),
	CONSTRAINT ck_nexhome_partner_deductions_status CHECK (deduction_status IN ('RECORDED', 'CANCELLED')),
	CONSTRAINT ck_nexhome_partner_deductions_cancelled CHECK (
		(deduction_status = 'CANCELLED') = (cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL
			AND cancellation_reason IS NOT NULL)),
	-- "Other" needs a note saying what it is for
	CONSTRAINT ck_nexhome_partner_deductions_other_notes CHECK (deduction_reason <> 'OTHER' OR notes IS NOT NULL)
);

CREATE INDEX ix_nexhome_partner_deductions_partner ON nexhome_partner_deductions (partner_id, deducted_on DESC);
CREATE INDEX ix_nexhome_partner_deductions_payout ON nexhome_partner_deductions (payout_id) WHERE payout_id IS NOT NULL;

INSERT INTO nexhome_lookup_types (type_code, type_name, description, active_flag, is_system_managed, created_by,
                                  updated_by)
VALUES ('DEDUCTION_REASON', 'Deduction Reason', 'Why NexHome kept part of what it owed a partner.', TRUE, TRUE, 1, 1);

INSERT INTO nexhome_lookup_values (lookup_type_id, value_code, display_name, display_order, active_flag, is_default,
                                   metadata, created_by, updated_by)
SELECT t.id, v.code, v.name, v.ord, TRUE, FALSE, '{}'::jsonb, 1, 1
FROM nexhome_lookup_types t
CROSS JOIN (VALUES ('PENALTY', 'Penalty', 1),
                   ('DAMAGE', 'Damage / Loss', 2),
                   ('CUSTOMER_COMPLAINT', 'Customer Complaint', 3),
                   ('ADVANCE_RECOVERY', 'Advance Recovery', 4),
                   ('OTHER', 'Other', 5)) AS v(code, name, ord)
WHERE t.type_code = 'DEDUCTION_REASON';
