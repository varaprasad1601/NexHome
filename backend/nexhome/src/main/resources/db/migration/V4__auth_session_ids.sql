-- Access tokens now belong to a login session: they carry its session_id ("sid" claim) and are accepted only while
-- the session has an unrevoked refresh token, so logging out stops the access token immediately.
-- Every refresh token of one login shares the session_id across rotations.
-- Sessions are disposable, so the table is rebuilt (keeping columns in model order); everyone signs in again.
DROP TABLE nexhome_auth_refresh_tokens;

CREATE TABLE nexhome_auth_refresh_tokens (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id        BIGINT      NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	session_id     UUID        NOT NULL,
	token_hash     VARCHAR(64) NOT NULL,
	expires_at     TIMESTAMPTZ NOT NULL,
	last_used_at   TIMESTAMPTZ,
	revoked_at     TIMESTAMPTZ,
	-- LOGOUT, LOGOUT_ALL, ROTATED, REUSE_DETECTED, ACCOUNT_STATUS_CHANGED
	revoked_reason VARCHAR(30),
	replaced_by_id BIGINT REFERENCES nexhome_auth_refresh_tokens (id),
	user_agent     VARCHAR(500),
	creation_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by     BIGINT REFERENCES nexhome_users (id),
	updated_date   TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by     BIGINT REFERENCES nexhome_users (id),
	attribute1     VARCHAR(255),
	attribute2     VARCHAR(255),
	attribute3     VARCHAR(255),
	attribute4     VARCHAR(255),
	attribute5     VARCHAR(255),
	CONSTRAINT uq_nexhome_auth_refresh_tokens_hash UNIQUE (token_hash),
	CONSTRAINT ck_nexhome_auth_refresh_tokens_revoked CHECK ((revoked_at IS NULL) = (revoked_reason IS NULL))
);

CREATE INDEX ix_nexhome_auth_refresh_tokens_user_active
	ON nexhome_auth_refresh_tokens (user_id) WHERE revoked_at IS NULL;
-- Checked on every authenticated request
CREATE INDEX ix_nexhome_auth_refresh_tokens_session_active
	ON nexhome_auth_refresh_tokens (session_id) WHERE revoked_at IS NULL;
CREATE INDEX ix_nexhome_auth_refresh_tokens_expires_at ON nexhome_auth_refresh_tokens (expires_at);
