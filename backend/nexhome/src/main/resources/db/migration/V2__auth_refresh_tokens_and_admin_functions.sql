-- Login sessions and the access rules of the identity/lookup endpoints.

-- ---------------------------------------------------------------------------------------------------------------
-- Refresh tokens (not in the design PDF): one row per login session. Only a SHA-256 hash of the token is stored.
-- Each refresh revokes the used token (ROTATED) and issues a new one; presenting a revoked token again revokes all
-- of the user's sessions (REUSE_DETECTED).
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE nexhome_auth_refresh_tokens (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id        BIGINT      NOT NULL REFERENCES nexhome_users (id) ON DELETE RESTRICT,
	token_hash     VARCHAR(64) NOT NULL,
	expires_at     TIMESTAMPTZ NOT NULL,
	last_used_at   TIMESTAMPTZ,
	revoked_at     TIMESTAMPTZ,
	-- LOGOUT, LOGOUT_ALL, ROTATED, REUSE_DETECTED, ACCOUNT_STATUS_CHANGED
	revoked_reason VARCHAR(30),
	replaced_by_id BIGINT REFERENCES nexhome_auth_refresh_tokens (id),
	user_agent     VARCHAR(500),
	creation_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
	created_by     BIGINT REFERENCES nexhome_users (id),
	updated_date   TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_by     BIGINT REFERENCES nexhome_users (id),
	attribute1     VARCHAR(255),
	attribute2     VARCHAR(255),
	attribute3     VARCHAR(255),
	attribute4     VARCHAR(255),
	attribute5     VARCHAR(255),
	CONSTRAINT uq_nexhome_auth_refresh_tokens_hash UNIQUE (token_hash),
	CONSTRAINT ck_nexhome_auth_refresh_tokens_revoked CHECK ((revoked_at IS NULL) = (revoked_reason IS NULL))
);

CREATE INDEX ix_nexhome_auth_refresh_tokens_user_active
	ON nexhome_auth_refresh_tokens (user_id) WHERE revoked_at IS NULL;
CREATE INDEX ix_nexhome_auth_refresh_tokens_expires_at ON nexhome_auth_refresh_tokens (expires_at);

-- ---------------------------------------------------------------------------------------------------------------
-- Functions guarding the admin endpoints. SUPER_USER always has full access and needs no role functions.
-- ---------------------------------------------------------------------------------------------------------------
INSERT INTO nexhome_functions (function_module, function_code, function_name, function_type, description,
                               created_by, updated_by)
VALUES ('LOOKUP', 'LOOKUP_MANAGE', 'Manage Lookups', 'FEATURE',
        'Read: list lookup types and all their values. Write: create and update lookup types and values.', 1, 1),
       ('IDENTITY', 'USER_MANAGE', 'Manage Users', 'FEATURE',
        'Read: view any user. Write: create users, update other users, change account status and roles.', 1, 1),
       ('IDENTITY', 'ROLE_MANAGE', 'Manage Roles', 'FEATURE',
        'Read: view roles. Write: create and update roles and their role functions. Delete: delete unused roles '
            || 'and role functions.', 1, 1),
       ('IDENTITY', 'FUNCTION_MANAGE', 'Manage Functions', 'FEATURE',
        'Read: view functions. Write: create and update functions. Delete: delete unused functions.', 1, 1);

-- ADMIN runs day-to-day administration; changing permissions (roles, functions) stays with SUPER_USER, otherwise an
-- admin could grant themselves anything. SUB_ADMIN can only look.
INSERT INTO nexhome_role_functions (role_id, function_id, can_read, can_write, can_delete, created_by, updated_by)
SELECT r.id, f.id, g.can_read, g.can_write, g.can_delete, 1, 1
FROM (VALUES ('ADMIN', 'LOOKUP_MANAGE', TRUE, TRUE, FALSE),
             ('ADMIN', 'USER_MANAGE', TRUE, TRUE, FALSE),
             ('ADMIN', 'ROLE_MANAGE', TRUE, FALSE, FALSE),
             ('ADMIN', 'FUNCTION_MANAGE', TRUE, FALSE, FALSE),
             ('SUB_ADMIN', 'LOOKUP_MANAGE', TRUE, FALSE, FALSE),
             ('SUB_ADMIN', 'USER_MANAGE', TRUE, FALSE, FALSE)) AS g (role_code, function_code, can_read, can_write,
                                                                    can_delete)
JOIN nexhome_roles r ON r.code = g.role_code
JOIN nexhome_functions f ON f.function_code = g.function_code;
