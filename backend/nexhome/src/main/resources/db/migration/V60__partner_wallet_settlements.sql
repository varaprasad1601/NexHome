-- ---------------------------------------------------------------------------------------------------------------
-- partner_settlements (not in the PDF): the partner's wallet paid out in one transfer.
-- The wallet holds what is not settled yet: online jobs' payouts (NexHome received the money; the partner is owed
-- the gross less commission plus adjustments) and cash jobs the partner collected (the partner kept the cash and
-- owes NexHome its commission). Settling pays the difference and links every item, so the wallet starts at 0.
-- ---------------------------------------------------------------------------------------------------------------
CREATE SEQUENCE nexhome_partner_settlements_public_id_seq;

CREATE TABLE nexhome_partner_settlements (
	id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	public_id            VARCHAR(24)    NOT NULL
		DEFAULT nexhome_public_id('NHSETL', nextval('nexhome_partner_settlements_public_id_seq')),
	partner_id           BIGINT         NOT NULL REFERENCES nexhome_partner_profiles (id) ON DELETE RESTRICT,
	bank_account_id      BIGINT REFERENCES nexhome_partner_bank_accounts (id) ON DELETE SET NULL,
	bank_account_last4   VARCHAR(4),
	bank_name            VARCHAR(150),
	cash_jobs            INTEGER        NOT NULL DEFAULT 0 CHECK (cash_jobs >= 0),
	cash_amount          NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (cash_amount >= 0),
	cash_commission      NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (cash_commission >= 0),
	online_jobs          INTEGER        NOT NULL DEFAULT 0 CHECK (online_jobs >= 0),
	online_amount        NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (online_amount >= 0),
	online_commission    NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (online_commission >= 0),
	adjustments_amount   NUMERIC(12, 2) NOT NULL DEFAULT 0,
	net_amount           NUMERIC(12, 2) NOT NULL CHECK (net_amount > 0),
	-- PAID (transferred) or FAILED (the transfer failed; nothing is linked to it)
	settlement_status    VARCHAR(20)    NOT NULL,
	provider_transfer_id VARCHAR(150),
	provider_response    JSONB,
	paid_at              TIMESTAMPTZ,
	creation_date        TIMESTAMPTZ    NOT NULL DEFAULT now(),
	created_by           BIGINT REFERENCES nexhome_users (id),
	updated_date         TIMESTAMPTZ    NOT NULL DEFAULT now(),
	updated_by           BIGINT REFERENCES nexhome_users (id),
	attribute1           VARCHAR(255),
	attribute2           VARCHAR(255),
	attribute3           VARCHAR(255),
	attribute4           VARCHAR(255),
	attribute5           VARCHAR(255),
	CONSTRAINT uq_nexhome_partner_settlements_public_id UNIQUE (public_id),
	CONSTRAINT ck_nexhome_partner_settlements_status CHECK (settlement_status IN ('PAID', 'FAILED')),
	CONSTRAINT ck_nexhome_partner_settlements_paid CHECK ((settlement_status = 'PAID') = (paid_at IS NOT NULL)),
	CONSTRAINT ck_nexhome_partner_settlements_net
		CHECK (net_amount = online_amount - online_commission + adjustments_amount - cash_commission)
);

CREATE INDEX ix_nexhome_partner_settlements_partner ON nexhome_partner_settlements (partner_id, creation_date DESC);

ALTER TABLE nexhome_partner_payouts
	ADD COLUMN settlement_id BIGINT REFERENCES nexhome_partner_settlements (id) ON DELETE RESTRICT;
ALTER TABLE nexhome_cash_collections
	ADD COLUMN settlement_id BIGINT REFERENCES nexhome_partner_settlements (id) ON DELETE RESTRICT;

CREATE INDEX ix_nexhome_partner_payouts_settlement ON nexhome_partner_payouts (settlement_id);
CREATE INDEX ix_nexhome_cash_collections_settlement ON nexhome_cash_collections (settlement_id);
